import { execFileSync } from "node:child_process";
/**
 * Regenerate release approval only after reviewing the plugin's executable closure.
 * Default mode checks committed approval. This script never imports analyzer code.
 */
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const pluginRoot = join(root, "packages/plugin-treesitter");
const manifest = JSON.parse(
  readFileSync(join(pluginRoot, "package.json"), "utf8"),
);
const runtimeRoot = dirname(
  createRequire(join(pluginRoot, "package.json")).resolve("web-tree-sitter"),
);
const runtime = JSON.parse(
  readFileSync(join(runtimeRoot, "package.json"), "utf8"),
);
if (
  JSON.stringify(Object.keys(manifest.dependencies ?? {}).sort()) !==
    '["web-tree-sitter"]' ||
  Object.keys(runtime.dependencies ?? {}).length !== 0
) {
  throw new Error(
    "Dependency closure changed; review and extend qualification before approval",
  );
}
if (manifest.dependencies["web-tree-sitter"] !== runtime.version)
  throw new Error("Runtime dependency must be pinned exactly");

function filesBelow(directory, prefix = "") {
  return readdirSync(join(directory, prefix), { withFileTypes: true }).flatMap(
    (entry) => {
      const name = prefix ? `${prefix}/${entry.name}` : entry.name;
      if (entry.isSymbolicLink())
        throw new Error(`Unexpected symlink in approved closure: ${name}`);
      return entry.isDirectory() ? filesBelow(directory, name) : [name];
    },
  );
}
function hashes(directory, files) {
  return Object.fromEntries(
    [...new Set(files)].sort().map((file) => {
      if (!statSync(join(directory, file)).isFile())
        throw new Error(`Missing approval input: ${file}`);
      return [
        file,
        createHash("sha256")
          .update(readFileSync(join(directory, file)))
          .digest("hex"),
      ];
    }),
  );
}
const approval = [
  {
    packageName: manifest.name,
    version: manifest.version,
    files: hashes(pluginRoot, [
      "package.json",
      "catalog.json",
      "integrity.json",
      "SBOM.spdx.json",
      "THIRD_PARTY_NOTICES.md",
      ...filesBelow(pluginRoot, "dist").filter((file) =>
        /\.(?:[cm]?js|json|wasm)$/.test(file),
      ),
      ...filesBelow(pluginRoot, "assets"),
      ...filesBelow(pluginRoot, "licenses"),
    ]),
    dependencies: [
      {
        packageName: runtime.name,
        version: runtime.version,
        files: hashes(
          runtimeRoot,
          filesBelow(runtimeRoot).filter(
            (file) =>
              /\.(?:[cm]?js|json|wasm)$/.test(file) || file === "LICENSE",
          ),
        ),
      },
    ],
  },
];
const destination =
  "packages/cli/src/plugins/approved-source-analyzers.generated.ts";
const source = `// Generated by scripts/qualify-source-analyzers.mjs after release qualification.\n// Do not approve changed bytes without reviewing the executable and asset closure.\n// implements REQ-source-analysis-v2\nexport const qualifiedSourceAnalyzers = ${JSON.stringify(approval, null, 2)} as const;\n`;
const formatted = execFileSync(
  join(root, "node_modules/.bin/biome"),
  ["format", `--stdin-file-path=${destination}`],
  { cwd: root, input: source, encoding: "utf8" },
);
if (process.argv.includes("--write")) {
  writeFileSync(join(root, destination), formatted);
  console.log(
    `Wrote release approval for ${manifest.name}@${manifest.version}`,
  );
} else if (readFileSync(join(root, destination), "utf8") !== formatted) {
  throw new Error(
    "Approved source analyzer closure is stale; review and run qualification with --write",
  );
} else {
  console.log(
    `Verified release approval for ${manifest.name}@${manifest.version}`,
  );
}
