/*
 Kibi — repo-local, per-branch, queryable long-term memory for software projects
 Copyright (C) 2026 Piotr Franczyk

 Generates every statement of the check-rule registry from
 packages/core/schema/rule-registry.json so the TS rule registry, the kb_check
 input enum, and the Prolog rule_registry facts cannot drift apart:

   - packages/cli/src/utils/rule-registry.generated.ts
   - packages/cli/src/public/operations/specs/check-rules.generated.ts
   - packages/core/src/rule_registry.pl

 --check compares the emitted files against the working tree and exits 1 on
 drift (used by CI).
*/
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "packages/core/schema/rule-registry.json");
const targets = {
  rulesTs: path.join(root, "packages/cli/src/utils/rule-registry.generated.ts"),
  specTs: path.join(
    root,
    "packages/cli/src/public/operations/specs/check-rules.generated.ts",
  ),
  prologFacts: path.join(root, "packages/core/src/rule_registry.pl"),
};

const ENFORCEMENT_CLASSES = new Set(["canonical", "advisory", "migration"]);
const CATEGORIES = new Set([
  "coverage",
  "integrity",
  "lifecycle",
  "traceability",
]);
const IMPLEMENTATIONS = new Set(["prolog", "typescript"]);

function escapeSingleQuotes(value) {
  return value.replace(/\\/g, "\\\\").replace(/'/g, "\\'");
}

function validate(rules) {
  const seen = new Set();
  for (const rule of rules) {
    for (const field of [
      "name",
      "description",
      "enforcementClass",
      "category",
      "implementation",
    ]) {
      if (typeof rule[field] !== "string" || rule[field].length === 0) {
        throw new Error(`Rule ${rule.name ?? "(unnamed)"}: ${field} is required`);
      }
    }
    if (seen.has(rule.name)) {
      throw new Error(`Duplicate rule name: ${rule.name}`);
    }
    seen.add(rule.name);
    if (!ENFORCEMENT_CLASSES.has(rule.enforcementClass)) {
      throw new Error(`Rule ${rule.name}: unknown enforcementClass`);
    }
    if (!CATEGORIES.has(rule.category)) {
      throw new Error(`Rule ${rule.name}: unknown category`);
    }
    if (!IMPLEMENTATIONS.has(rule.implementation)) {
      throw new Error(`Rule ${rule.name}: unknown implementation`);
    }
    if (rule.implementation === "prolog") {
      if (typeof rule.prologPredicate !== "string") {
        throw new Error(`Rule ${rule.name}: prologPredicate is required`);
      }
      if (![1, 2].includes(rule.prologPredicateArity)) {
        throw new Error(`Rule ${rule.name}: prologPredicateArity must be 1 or 2`);
      }
    } else if (rule.prologPredicate !== null) {
      throw new Error(
        `Rule ${rule.name}: typescript rules must not declare prologPredicate`,
      );
    }
  }
}

function renderRulesTs(rules) {
  const entries = rules
    .map((rule) => {
      const fields = [
        `    name: ${JSON.stringify(rule.name)},`,
        `    description: ${JSON.stringify(rule.description)},`,
        `    enforcementClass: ${JSON.stringify(rule.enforcementClass)},`,
        `    category: ${JSON.stringify(rule.category)},`,
      ];
      return `  {\n${fields.join("\n")}\n  },`;
    })
    .join("\n");
  return `/*
 * Kibi — repo-local, per-branch, queryable long-term memory for software projects
 * Copyright (C) 2026 Piotr Franczyk
 *
 * This file is generated by scripts/generate-rule-registry.mjs from
 * packages/core/schema/rule-registry.json. Do not edit it directly; edit the
 * JSON source and regenerate.
 */

// implements REQ-006
export const GENERATED_RULES = [
${entries}
] as const;
`;
}

function renderSpecTs(rules) {
  const names = rules.map((rule) => JSON.stringify(rule.name));
  const allowed = rules.map((rule) => rule.name).join(", ");
  return `/*
 * Kibi — repo-local, per-branch, queryable long-term memory for software projects
 * Copyright (C) 2026 Piotr Franczyk
 *
 * This file is generated by scripts/generate-rule-registry.mjs from
 * packages/core/schema/rule-registry.json. Do not edit it directly; edit the
 * JSON source and regenerate.
 */

// implements REQ-006
/** Every selectable kb_check rule name, registry order. */
export const SELECTABLE_RULE_NAMES: readonly string[] = [
  ${names.join(",\n  ")},
];

// implements REQ-006
/** Comma-separated "Allowed:" fragment for the kb_check rules description. */
export const SELECTABLE_RULES_ALLOWED = "${allowed}";
`;
}

function renderPrologFacts(rules) {
  const known = [];
  const classes = [];
  const implementations = [];
  const predicates = [];
  const arities = [];
  const descriptions = [];
  for (const rule of rules) {
    known.push(`known_rule('${rule.name}').`);
    classes.push(
      `rule_enforcement_class('${rule.name}', ${rule.enforcementClass}).`,
    );
    implementations.push(
      `rule_implementation('${rule.name}', ${rule.implementation}).`,
    );
    if (rule.prologPredicate) {
      predicates.push(`rule_predicate('${rule.name}', ${rule.prologPredicate}).`);
      arities.push(
        `rule_predicate_arity('${rule.name}', ${rule.prologPredicateArity}).`,
      );
    }
    descriptions.push(
      `rule_description('${rule.name}', '${escapeSingleQuotes(rule.description)}').`,
    );
  }
  const blocks = [
    known.join("\n"),
    classes.join("\n"),
    implementations.join("\n"),
    predicates.join("\n"),
    arities.join("\n"),
    descriptions.join("\n"),
  ];
  return `% Module: rule_registry
% GENERATED by scripts/generate-rule-registry.mjs from
% packages/core/schema/rule-registry.json. Do not edit directly.
%
% Registry facts shared by TS and Prolog so unknown rule names fail loudly
% instead of silently returning empty results.

:- module(rule_registry, [
    known_rule/1,
    rule_enforcement_class/2,
    rule_implementation/2,
    rule_predicate/2,
    rule_predicate_arity/2,
    rule_description/2
]).

${blocks.join("\n\n")}
`;
}

async function main() {
  const source = JSON.parse(await readFile(sourcePath, "utf8"));
  const rules = source.rules;
  if (!Array.isArray(rules) || rules.length === 0) {
    throw new Error("rule-registry.json must define a non-empty rules array");
  }
  validate(rules);

  const outputs = new Map([
    [targets.rulesTs, renderRulesTs(rules)],
    [targets.specTs, renderSpecTs(rules)],
    [targets.prologFacts, renderPrologFacts(rules)],
  ]);

  if (process.argv.includes("--check")) {
    let drifted = false;
    for (const [file, content] of outputs) {
      const current = await readFile(file, "utf8");
      if (current !== content) {
        console.error(`Out of date: ${path.relative(root, file)}`);
        drifted = true;
      }
    }
    if (drifted) {
      throw new Error(
        "Generated rule registry files are stale; run: node scripts/generate-rule-registry.mjs",
      );
    }
    return;
  }

  for (const [file, content] of outputs) {
    await writeFile(file, content, "utf8");
  }
}

await main();
