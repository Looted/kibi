import { execFileSync } from "node:child_process";
import { closeSync, openSync, readFileSync, readSync } from "node:fs";
import { join } from "node:path";

/**
 * The comment generators put at the top of the files they write: Go's
 * `Code generated ... DO NOT EDIT.`, `@generated` (tree-sitter, Facebook
 * tooling), protobuf's `DO NOT EDIT!`, bindgen's `automatically generated`.
 */
const GENERATED_HEADER =
  /@generated\b|\bDO NOT EDIT\b|\bauto-?generated\b|\bautomatically generated\b|\bcode generated by\b|\bthis file (?:is|was|has been) (?:auto-?)?generated\b/i;

/** Lines from the top of a file in which a generator marker counts. */
const HEADER_LINES = 5;
const HEADER_BYTES = 1024;

/** Whether the first lines of a file carry a standard generator marker. */
// implements REQ-kibi-tree-sitter-language-packs
export function hasGeneratedHeader(content: string): boolean {
  return GENERATED_HEADER.test(
    content
      .slice(0, HEADER_BYTES)
      .split("\n")
      .slice(0, HEADER_LINES)
      .join("\n"),
  );
}

/**
 * Paths git marks `linguist-generated` or `linguist-vendored` through
 * `.gitattributes`. Empty when git cannot answer.
 */
// implements REQ-kibi-tree-sitter-language-packs
export function gitAttributeGeneratedPaths(
  workspaceRoot: string,
  files: readonly string[],
): ReadonlySet<string> {
  if (files.length === 0) return new Set();
  let output: string;
  try {
    output = execFileSync(
      "git",
      [
        "check-attr",
        "-z",
        "--stdin",
        "linguist-generated",
        "linguist-vendored",
      ],
      {
        cwd: workspaceRoot,
        encoding: "utf8",
        input: `${files.join("\0")}\0`,
        stdio: ["pipe", "pipe", "ignore"],
        maxBuffer: 64 * 1024 * 1024,
      },
    );
  } catch {
    return new Set();
  }
  // -z output is path NUL attribute NUL value NUL, repeated.
  const fields = output.split("\0");
  const generated = new Set<string>();
  for (let index = 0; index + 2 < fields.length; index += 3) {
    const value = fields[index + 2];
    if (value === "set" || value === "true")
      generated.add(fields[index] as string);
  }
  return generated;
}

function readHead(path: string): string {
  let descriptor: number | undefined;
  try {
    descriptor = openSync(path, "r");
    const buffer = Buffer.alloc(HEADER_BYTES);
    const read = readSync(descriptor, buffer, 0, HEADER_BYTES, 0);
    return buffer.subarray(0, read).toString("utf8");
  } catch {
    return "";
  } finally {
    if (descriptor !== undefined) closeSync(descriptor);
  }
}

/**
 * The tracked files among `files` that a tool wrote rather than a person:
 * marked generated or vendored in `.gitattributes`, or opening with a
 * generator marker.
 */
// implements REQ-kibi-tree-sitter-language-packs
export function generatedSourceFiles(
  workspaceRoot: string,
  files: readonly string[],
): ReadonlySet<string> {
  const generated = new Set(gitAttributeGeneratedPaths(workspaceRoot, files));
  for (const file of files)
    if (
      !generated.has(file) &&
      hasGeneratedHeader(readHead(join(workspaceRoot, file)))
    )
      generated.add(file);
  return generated;
}

/** Whether one file is generated, by its attributes or its own text. */
// implements REQ-kibi-tree-sitter-language-packs
export function isGeneratedSource(
  workspaceRoot: string,
  file: string,
  content: string,
): boolean {
  return (
    hasGeneratedHeader(content) ||
    gitAttributeGeneratedPaths(workspaceRoot, [file]).has(file)
  );
}

/**
 * The paths among `candidates` that a tracked KB file mentions: a symbol's
 * sourceFile, a proof contract's files, or any other entity field. Reads the
 * tracked `.kb/` text only.
 */
// implements REQ-kibi-tree-sitter-language-packs
export function kbReferencedFiles(
  workspaceRoot: string,
  kbFiles: readonly string[],
  candidates: readonly string[],
): ReadonlySet<string> {
  if (candidates.length === 0) return new Set();
  const referenced = new Set<string>();
  let remaining = [...candidates];
  for (const kbFile of kbFiles) {
    if (remaining.length === 0) break;
    let text: string;
    try {
      text = readFileSync(join(workspaceRoot, kbFile), "utf8");
    } catch {
      continue;
    }
    remaining = remaining.filter((candidate) => {
      if (!mentions(text, candidate)) return true;
      referenced.add(candidate);
      return false;
    });
  }
  return referenced;
}

/** Whether `text` names `path` as a whole path, not inside a longer one. */
function mentions(text: string, path: string): boolean {
  let from = text.indexOf(path);
  while (from !== -1) {
    const before = from === 0 ? "" : text.charAt(from - 1);
    const after = text.charAt(from + path.length);
    if (
      !/[\w./-]/.test(before) &&
      !/[\w/-]/.test(after) &&
      !/^\.\w/.test(text.slice(from + path.length, from + path.length + 2))
    )
      return true;
    from = text.indexOf(path, from + 1);
  }
  return false;
}
