import { execFileSync } from "node:child_process";
import { closeSync, openSync, readFileSync, readSync } from "node:fs";
import { join } from "node:path";
import ignore from "ignore";

/**
 * The comment generators put at the top of the files they write: Go's
 * `Code generated ... DO NOT EDIT.`, `@generated` (tree-sitter, Facebook
 * tooling), protobuf's `DO NOT EDIT!`, bindgen's `automatically generated`.
 */
const GENERATED_HEADER =
  /@generated\b|\bDO NOT EDIT\b|\bauto-?generated\b|\bautomatically generated\b|\bcode generated by\b|\bthis file (?:is|was|has been) generated\b/i;

/** Lines from the top of a file in which a generator marker counts. */
const HEADER_LINES = 5;
const HEADER_BYTES = 1024;

/** Whether the first lines of a file carry a standard generator marker. */
export function hasGeneratedHeader(content: string | undefined): boolean {
  return (
    content !== undefined &&
    GENERATED_HEADER.test(
      content
        .slice(0, HEADER_BYTES)
        .split("\n")
        .slice(0, HEADER_LINES)
        .join("\n"),
    )
  );
}

/**
 * How a project marks generated files beyond `.gitattributes` and headers:
 * `package.json` `kibi.generatedPaths`, gitignore-style globs where a `!`
 * pattern marks a path as hand-written. `attributeSource` reads
 * `.gitattributes` from that tree instead of the working tree, so a staged
 * change cannot mark its own files generated.
 */
export type GeneratedOptions = Readonly<{
  patterns?: readonly string[];
  attributeSource?: string;
}>;

/**
 * What `.gitattributes` says about each path: true when `linguist-generated`
 * or `linguist-vendored` is set, false when one is explicitly unset or false
 * and none is set. Paths git says nothing about are absent. Empty when git
 * cannot answer (an unknown tree reads as no attributes).
 */
export function gitAttributeVerdicts(
  workspaceRoot: string,
  files: readonly string[],
  attributeSource?: string,
): ReadonlyMap<string, boolean> {
  const verdicts = new Map<string, boolean>();
  if (files.length === 0) return verdicts;
  let output: string;
  try {
    output = execFileSync(
      "git",
      [
        "check-attr",
        "-z",
        "--stdin",
        ...(attributeSource === undefined
          ? []
          : [`--source=${attributeSource}`]),
        "linguist-generated",
        "linguist-vendored",
      ],
      {
        cwd: workspaceRoot,
        encoding: "utf8",
        input: `${files.join("\0")}\0`,
        // rationale: [] pipes stderr into the discarded result instead of ignoring it; with stdio given, neither reaches the terminal
        // Stryker disable next-line ArrayDeclaration
        stdio: ["pipe", "pipe", "ignore"],
        maxBuffer: 64 * 1024 * 1024,
      },
    );
  } catch {
    return verdicts;
  }
  // -z output is path NUL attribute NUL value NUL, repeated.
  for (const match of output.matchAll(/([^\0]*)\0[^\0]*\0([^\0]*)\0/g)) {
    const file = match[1] as string;
    const value = match[2];
    if (value === "set" || value === "true") verdicts.set(file, true);
    else if (
      (value === "unset" || value === "false") &&
      verdicts.get(file) !== true
    )
      verdicts.set(file, false);
  }
  return verdicts;
}

/** The first bytes of a file as text; empty when it cannot be read. */
function readHead(path: string): string {
  const buffer = Buffer.alloc(HEADER_BYTES);
  let read = 0;
  let descriptor: number | undefined;
  try {
    descriptor = openSync(path, "r");
    read = readSync(descriptor, buffer, 0, HEADER_BYTES, 0);
  } catch {
    // An unreadable file has no header.
  } finally {
    if (descriptor !== undefined) closeSync(descriptor);
  }
  return buffer.subarray(0, read).toString();
}

/**
 * Decides whether files are generated, in this order: a `kibi.generatedPaths`
 * pattern (a `!` pattern says hand-written), then `.gitattributes`
 * (`linguist-generated=false` says hand-written), then a generator header in
 * the text the caller supplies. `files` are the paths the attributes are
 * read for up front; other paths are asked of git one at a time.
 */
export function generatedClassifier(
  workspaceRoot: string,
  files: readonly string[],
  options: GeneratedOptions = {},
): (file: string, text: () => string | undefined) => boolean {
  const matcher = ignore();
  if (options.patterns) matcher.add([...options.patterns]);
  const attributes = new Map<string, boolean | undefined>(
    gitAttributeVerdicts(workspaceRoot, files, options.attributeSource),
  );
  const asked = new Set(files);
  return (file, text) => {
    const pattern = matcher.test(file);
    if (pattern.unignored) return false;
    if (pattern.ignored) return true;
    if (!asked.has(file)) {
      asked.add(file);
      attributes.set(
        file,
        gitAttributeVerdicts(
          workspaceRoot,
          [file],
          options.attributeSource,
        ).get(file),
      );
    }
    const attribute = attributes.get(file);
    if (attribute !== undefined) return attribute;
    return hasGeneratedHeader(text());
  };
}

/**
 * The tracked files among `files` that a tool wrote rather than a person:
 * listed in kibi.generatedPaths, marked generated or vendored in
 * `.gitattributes`, or opening with a generator marker.
 */
export function generatedSourceFiles(
  workspaceRoot: string,
  files: readonly string[],
  options: GeneratedOptions = {},
): ReadonlySet<string> {
  const generated = generatedClassifier(workspaceRoot, files, options);
  return new Set(
    files.filter((file) =>
      generated(file, () => readHead(join(workspaceRoot, file))),
    ),
  );
}

/** Whether one file is generated, by the project's patterns, its attributes or its own text. */
export function isGeneratedSource(
  workspaceRoot: string,
  file: string,
  content: string,
  options: GeneratedOptions = {},
): boolean {
  // Git is asked only when no pattern decides.
  return generatedClassifier(workspaceRoot, [], options)(file, () => content);
}

/**
 * The staged paths a tool generated, judged only by what was committed
 * before the change: kibi.generatedPaths and `.gitattributes` from the base
 * tree, and a generator header in the committed version of the file. A
 * change cannot make its own files generated by adding a header or an
 * attribute.
 */
export function stagedGeneratedPaths(
  workspaceRoot: string,
  inventory: readonly Readonly<{ path: string; previousContent?: string }>[],
  patterns: readonly string[] | undefined,
  baseTree: string,
): ReadonlySet<string> {
  const files = inventory.map((entry) => entry.path);
  const generated = generatedClassifier(workspaceRoot, files, {
    ...(patterns ? { patterns } : {}),
    attributeSource: baseTree,
  });
  return new Set(
    inventory
      .filter((entry) => generated(entry.path, () => entry.previousContent))
      .map((entry) => entry.path),
  );
}

/**
 * The paths among `candidates` that a tracked KB file mentions: a symbol's
 * sourceFile, a proof contract's files, or any other entity field. Reads the
 * tracked `.kb/` text only.
 */
export function kbReferencedFiles(
  workspaceRoot: string,
  kbFiles: readonly string[],
  candidates: readonly string[],
): ReadonlySet<string> {
  const referenced = new Set<string>();
  for (const kbFile of kbFiles) {
    // rationale: once every candidate is found the rest of the KB is not read; the result is the same either way
    // Stryker disable next-line ConditionalExpression
    if (referenced.size === candidates.length) break;
    let text: string;
    try {
      text = readFileSync(join(workspaceRoot, kbFile), "utf8");
    } catch {
      continue;
    }
    for (const candidate of candidates)
      if (mentions(text, candidate)) referenced.add(candidate);
  }
  return referenced;
}

const CONTINUES_PATH = /[\w/-]|\.\w/y;

/** Whether `text` names `path` as a whole path, not inside a longer one. */
function mentions(text: string, path: string): boolean {
  let from = text.indexOf(path);
  while (from !== -1) {
    // A word character, `/`, `-` or `.word` after the path continues it.
    CONTINUES_PATH.lastIndex = from + path.length;
    if (!/[\w./-]/.test(text.charAt(from - 1)) && !CONTINUES_PATH.test(text))
      return true;
    from = text.indexOf(path, from + 1);
  }
  return false;
}
