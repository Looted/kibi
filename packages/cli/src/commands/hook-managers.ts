import { existsSync, readFileSync, statSync } from "node:fs";
import * as path from "node:path";
import { parse as parseYaml } from "yaml";
import {
  MANAGED_HOOK_NAMES,
  type ManagedHookName,
  hookDelegationSnippet,
} from "./init-helpers.js";

/** Git hook managers whose configuration Kibi can print and read. */
export const HOOK_MANAGER_NAMES = ["lefthook", "husky", "pre-commit"] as const;

export type HookManagerName = (typeof HOOK_MANAGER_NAMES)[number];

/** Formats `kibi init --print-hook` can emit. */
export const HOOK_SNIPPET_FORMATS = ["shell", ...HOOK_MANAGER_NAMES] as const;

export type HookSnippetFormat = (typeof HOOK_SNIPPET_FORMATS)[number];

export interface DetectedHookManager {
  name: HookManagerName;
  /** Repository-relative file or directory that holds the hook definitions. */
  configPath: string;
}

// lefthook reads the first of these it finds; the -local variants are merged
// on top of the main file.
const LEFTHOOK_CONFIG_FILES = [
  "lefthook.yml",
  ".lefthook.yml",
  "lefthook.yaml",
  ".lefthook.yaml",
  "lefthook.json",
  ".lefthook.json",
  "lefthook.jsonc",
  ".lefthook.jsonc",
  "lefthook.toml",
  ".lefthook.toml",
  ".config/lefthook.yml",
  ".config/lefthook.yaml",
] as const;

const LEFTHOOK_LOCAL_CONFIG_FILES = [
  "lefthook-local.yml",
  ".lefthook-local.yml",
  "lefthook-local.yaml",
  ".lefthook-local.yaml",
  "lefthook-local.json",
  ".lefthook-local.json",
] as const;

const PRE_COMMIT_CONFIG_FILE = ".pre-commit-config.yaml";
const HUSKY_DIR = ".husky";

/** Hooks in the order a reader expects them: the commit gate first. */
const PRINT_ORDER: readonly ManagedHookName[] = [
  "pre-commit",
  "post-checkout",
  "post-merge",
  "post-rewrite",
];

// The local runner every Node.js install ships with. `--no-install` never
// downloads a kibi outside the project lockfile.
const KIBI_COMMAND = "npx --no-install kibi";

function isFile(filePath: string): boolean {
  try {
    return statSync(filePath).isFile();
  } catch {
    return false;
  }
}

function isDirectory(filePath: string): boolean {
  try {
    return statSync(filePath).isDirectory();
  } catch {
    return false;
  }
}

function readText(filePath: string): string | null {
  try {
    return readFileSync(filePath, "utf8");
  } catch {
    return null;
  }
}

function firstExisting(
  root: string,
  candidates: readonly string[],
): string | null {
  return candidates.find((file) => isFile(path.join(root, file))) ?? null;
}

/**
 * Which manager generated a hook file, from the marker text each one emits.
 * husky is recognized by core.hooksPath instead: its hook files are the
 * project's own scripts, which may mention husky without being generated.
 */
function hookFileManager(content: string): HookManagerName | null {
  if (content.includes("File generated by pre-commit")) return "pre-commit";
  if (/\blefthook\b/.test(content)) return "lefthook";
  return null;
}

function managerConfigPath(
  worktreeRoot: string,
  name: HookManagerName,
): string {
  switch (name) {
    case "lefthook":
      return (
        firstExisting(worktreeRoot, LEFTHOOK_CONFIG_FILES) ?? "lefthook.yml"
      );
    case "husky":
      return HUSKY_DIR;
    case "pre-commit":
      return PRE_COMMIT_CONFIG_FILE;
  }
}

/**
 * The hook manager that owns this repository's Git hooks, if any. Installed
 * hook files are the strongest evidence (they show what Git runs today), then
 * a core.hooksPath pointing into `.husky`, then a manager configuration file
 * that has not been installed yet.
 */
// implements REQ-git-hook-manager-integration
export function detectHookManager(
  worktreeRoot: string,
  effectiveHooksDir: string,
  hooksPathConfig: string | null = null,
): DetectedHookManager | null {
  const found = (name: HookManagerName): DetectedHookManager => ({
    name,
    configPath: managerConfigPath(worktreeRoot, name),
  });
  for (const hook of MANAGED_HOOK_NAMES) {
    const content = readText(path.join(effectiveHooksDir, hook));
    const manager = content === null ? null : hookFileManager(content);
    if (manager) return found(manager);
  }
  if (
    hooksPathConfig !== null &&
    /(?:^|[\\/])\.husky(?:[\\/]_)?[\\/]?$/.test(hooksPathConfig.trim())
  ) {
    return found("husky");
  }
  if (firstExisting(worktreeRoot, LEFTHOOK_CONFIG_FILES)) {
    return found("lefthook");
  }
  if (isDirectory(path.join(worktreeRoot, HUSKY_DIR))) return found("husky");
  if (isFile(path.join(worktreeRoot, PRE_COMMIT_CONFIG_FILE))) {
    return found("pre-commit");
  }
  return null;
}

function parseConfig(filePath: string): unknown {
  const text = readText(filePath);
  if (text === null) return undefined;
  try {
    return parseYaml(text);
  } catch {
    return undefined;
  }
}

function asRecord(value: unknown): Record<string, unknown> | null {
  return value !== null && typeof value === "object" && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : null;
}

/**
 * Every shell command lefthook runs for one hook: `run` strings of commands
 * and jobs (including nested groups), plus the contents of the scripts it
 * executes from `.lefthook/<hook>/`.
 */
function lefthookRuns(
  node: unknown,
  scriptDir: string,
  commands: string[],
): void {
  if (Array.isArray(node)) {
    for (const item of node) lefthookRuns(item, scriptDir, commands);
    return;
  }
  const record = asRecord(node);
  if (!record) return;
  for (const [key, value] of Object.entries(record)) {
    if (key === "run" && typeof value === "string") {
      commands.push(value);
    } else if (key === "script" && typeof value === "string") {
      const script = readText(path.join(scriptDir, value));
      if (script !== null) commands.push(script);
    } else if (key === "scripts" && asRecord(value)) {
      for (const name of Object.keys(value as Record<string, unknown>)) {
        const script = readText(path.join(scriptDir, name));
        if (script !== null) commands.push(script);
      }
    } else {
      lefthookRuns(value, scriptDir, commands);
    }
  }
}

function lefthookCommands(
  worktreeRoot: string,
  hook: ManagedHookName,
): string[] | null {
  const main = firstExisting(worktreeRoot, LEFTHOOK_CONFIG_FILES);
  const files = [
    ...(main ? [main] : []),
    ...LEFTHOOK_LOCAL_CONFIG_FILES.filter((file) =>
      isFile(path.join(worktreeRoot, file)),
    ),
  ];
  let configured = false;
  const commands: string[] = [];
  for (const file of files) {
    // TOML configs are not read; their hooks count as not visible.
    const hookNode = asRecord(parseConfig(path.join(worktreeRoot, file)))?.[
      hook
    ];
    if (hookNode === undefined || hookNode === null) continue;
    configured = true;
    lefthookRuns(
      hookNode,
      path.join(worktreeRoot, ".lefthook", hook),
      commands,
    );
  }
  return configured ? commands : null;
}

// pre-commit stage names before 3.2 dropped the `pre-` prefix.
const LEGACY_PRE_COMMIT_STAGES: Readonly<Record<string, string>> = {
  commit: "pre-commit",
  push: "pre-push",
  "merge-commit": "pre-merge-commit",
};

function preCommitFrameworkCommands(
  worktreeRoot: string,
  hook: ManagedHookName,
): string[] | null {
  const config = asRecord(
    parseConfig(path.join(worktreeRoot, PRE_COMMIT_CONFIG_FILE)),
  );
  if (!config || !Array.isArray(config.repos)) return null;
  const defaultStages = Array.isArray(config.default_stages)
    ? config.default_stages
    : null;
  let configured = false;
  const commands: string[] = [];
  for (const repo of config.repos) {
    const hooks = asRecord(repo)?.hooks;
    if (!Array.isArray(hooks)) continue;
    for (const entry of hooks) {
      const definition = asRecord(entry);
      if (!definition) continue;
      const stages = Array.isArray(definition.stages)
        ? definition.stages
        : defaultStages;
      const runsHere =
        stages === null
          ? hook === "pre-commit"
          : stages.some(
              (stage) =>
                typeof stage === "string" &&
                (LEGACY_PRE_COMMIT_STAGES[stage] ?? stage) === hook,
            );
      if (!runsHere) continue;
      configured = true;
      // Only local hooks carry a shell entry; remote hooks are opaque here.
      if (typeof definition.entry === "string") {
        const args = Array.isArray(definition.args)
          ? definition.args.filter((arg) => typeof arg === "string")
          : [];
        commands.push([definition.entry, ...args].join(" "));
      }
    }
  }
  return configured ? commands : null;
}

/**
 * The commands a hook manager runs for one Git hook, read from its
 * configuration, or null when the manager does not define that hook (or its
 * configuration cannot be read).
 */
// implements REQ-git-hook-manager-integration
export function hookManagerCommands(
  manager: HookManagerName,
  worktreeRoot: string,
  hook: ManagedHookName,
): string[] | null {
  switch (manager) {
    case "lefthook":
      return lefthookCommands(worktreeRoot, hook);
    case "husky": {
      const script = readText(path.join(worktreeRoot, HUSKY_DIR, hook));
      return script === null ? null : [script];
    }
    case "pre-commit":
      return preCommitFrameworkCommands(worktreeRoot, hook);
  }
}

/**
 * Individual shell commands of a hook script, ignoring comments. Lines are
 * split on command separators so `a && b` counts as two commands.
 */
function splitShellCommands(content: string): string[] {
  return content
    .split("\n")
    .filter((line) => !line.trimStart().startsWith("#"))
    .flatMap((line) => line.split(/&&|\|\||;|\|/))
    .map((command) => command.trim())
    .filter((command) => command.length > 0);
}

// Matches `kibi <sub>`, `npx kibi <sub>`, `node_modules/.bin/kibi <sub>` and
// the template's `"$KIBI_BIN" <sub>`.
function invokesKibi(command: string, subcommand: string): boolean {
  return new RegExp(
    `(?:\\bkibi|\\bKIBI_BIN)["'}]*\\s+${subcommand}(?=[\\s"']|$)`,
  ).test(command);
}

// A flag ends at whitespace, a closing quote (`sh -c '... --staged'`) or the
// end of the command.
function hasFlag(command: string, flag: string): boolean {
  return new RegExp(`\\s${flag}(?=[\\s"']|$)`).test(command);
}

/** The commands each Kibi-managed hook template runs. */
const KIBI_HOOK_DELEGATIONS: Readonly<
  Record<
    ManagedHookName,
    readonly {
      readonly label: string;
      readonly matches: (command: string) => boolean;
    }[]
  >
> = (() => {
  const sync = [
    {
      label: "kibi sync",
      matches: (command: string) => invokesKibi(command, "sync"),
    },
  ];
  return {
    "pre-commit": [
      {
        label: "kibi check-generated --staged --changed-only",
        matches: (command: string) =>
          invokesKibi(command, "check-generated") &&
          hasFlag(command, "--staged") &&
          hasFlag(command, "--changed-only"),
      },
      {
        label: "kibi check --staged",
        matches: (command: string) =>
          invokesKibi(command, "check") && hasFlag(command, "--staged"),
      },
    ],
    "post-checkout": sync,
    "post-merge": sync,
    "post-rewrite": sync,
  };
})();

/** Labels of the Kibi commands a hook definition never visibly runs. */
// implements REQ-git-hook-manager-integration
export function missingKibiHookCommands(
  hook: ManagedHookName,
  scripts: readonly string[],
): string[] {
  const commands = scripts.flatMap(splitShellCommands);
  return KIBI_HOOK_DELEGATIONS[hook]
    .filter((delegation) => !commands.some(delegation.matches))
    .map((delegation) => delegation.label);
}

function ordered(hooks: readonly ManagedHookName[]): ManagedHookName[] {
  return PRINT_ORDER.filter((hook) => hooks.includes(hook));
}

// Runs in lefthook's shell, where {N} is the Nth Git hook argument.
const LEFTHOOK_RUNS: Readonly<Record<ManagedHookName, string>> = {
  "pre-commit": `${KIBI_COMMAND} check-generated --staged --changed-only && ${KIBI_COMMAND} check --staged`,
  "post-checkout": `if [ "{3}" = "1" ]; then ${KIBI_COMMAND} sync; fi`,
  "post-merge": `${KIBI_COMMAND} sync`,
  "post-rewrite": `if [ "{1}" = "rebase" ]; then ${KIBI_COMMAND} sync; fi`,
};

function lefthookSnippet(hooks: readonly ManagedHookName[]): string {
  const lines = [
    "# Kibi git hook commands for lefthook. Merge these entries into your",
    "# lefthook.yml (keep your existing commands), then run 'lefthook install'.",
  ];
  for (const hook of hooks) {
    lines.push(`${hook}:`, "  commands:");
    if (hook === "post-checkout") {
      lines.push(
        "    # {3} is 1 for a branch checkout, 0 for a file checkout.",
      );
    }
    lines.push(
      `    ${hook === "pre-commit" ? "kibi-check" : "kibi-sync"}:`,
      `      run: ${LEFTHOOK_RUNS[hook]}`,
    );
  }
  return `${lines.join("\n")}\n`;
}

// pre-commit exposes post-checkout and post-rewrite arguments as variables.
const PRE_COMMIT_FRAMEWORK_HOOKS: Readonly<
  Record<ManagedHookName, { id: string; name: string; entry: string }>
> = {
  "pre-commit": {
    id: "kibi-check",
    name: "kibi check --staged",
    entry: `sh -c '${KIBI_COMMAND} check-generated --staged --changed-only && ${KIBI_COMMAND} check --staged'`,
  },
  "post-checkout": {
    id: "kibi-sync-checkout",
    name: "kibi sync (branch checkout)",
    entry: `sh -c 'if [ "$PRE_COMMIT_CHECKOUT_TYPE" = "1" ]; then ${KIBI_COMMAND} sync; fi'`,
  },
  "post-merge": {
    id: "kibi-sync-merge",
    name: "kibi sync (merge)",
    entry: `${KIBI_COMMAND} sync`,
  },
  "post-rewrite": {
    id: "kibi-sync-rebase",
    name: "kibi sync (rebase)",
    entry: `sh -c 'if [ "$PRE_COMMIT_REWRITE_COMMAND" = "rebase" ]; then ${KIBI_COMMAND} sync; fi'`,
  },
};

function preCommitFrameworkSnippet(hooks: readonly ManagedHookName[]): string {
  const lines = [
    "# Kibi git hooks for the pre-commit framework. Merge into your",
    "# .pre-commit-config.yaml (add the hook types to any existing",
    "# default_install_hook_types and the hooks to a local repo), then run",
    `# 'pre-commit install'.`,
    `default_install_hook_types: [${hooks.join(", ")}]`,
    "repos:",
    "  - repo: local",
    "    hooks:",
  ];
  for (const hook of hooks) {
    const definition = PRE_COMMIT_FRAMEWORK_HOOKS[hook];
    lines.push(
      `      - id: ${definition.id}`,
      `        name: ${definition.name}`,
      `        entry: ${definition.entry}`,
      "        language: system",
      "        pass_filenames: false",
      "        always_run: true",
      `        stages: [${hook}]`,
    );
  }
  return `${lines.join("\n")}\n`;
}

/**
 * Configuration that wires the given hooks to the commands Kibi's managed
 * templates run, in a hook manager's own format. `shell` and `husky` print
 * the hook-script snippets of `kibi init --print-hook`.
 */
// implements REQ-git-hook-manager-integration
export function hookManagerSnippet(
  format: HookSnippetFormat,
  hooks: readonly ManagedHookName[],
): string {
  const selected = ordered(hooks);
  switch (format) {
    case "shell":
      return selected.map(hookDelegationSnippet).join("\n");
    case "husky":
      return selected
        .map(
          (hook) =>
            `# --- ${HUSKY_DIR}/${hook} ---\n${hookDelegationSnippet(hook)}`,
        )
        .join("\n");
    case "lefthook":
      return lefthookSnippet(selected);
    case "pre-commit":
      return preCommitFrameworkSnippet(selected);
  }
}

export interface HookManagerCoverage {
  hook: ManagedHookName;
  /** Kibi commands the manager's definition of this hook does not visibly run. */
  missing: string[];
  /** Whether the manager defines the hook at all. */
  configured: boolean;
}

/** What each Kibi-managed hook looks like in the manager's configuration. */
// implements REQ-git-hook-manager-integration
export function hookManagerCoverage(
  manager: HookManagerName,
  worktreeRoot: string,
): HookManagerCoverage[] {
  return ordered(MANAGED_HOOK_NAMES).map((hook) => {
    const commands = hookManagerCommands(manager, worktreeRoot, hook);
    return {
      hook,
      configured: commands !== null,
      missing: missingKibiHookCommands(hook, commands ?? []),
    };
  });
}
