// executable_for TEST-kibi-tree-sitter-language-packs
import { afterEach, beforeEach, describe, expect, test } from "bun:test";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import { execSync, spawnSync } from "../helpers/isolated-env.js";

const TEST_TIMEOUT_MS = 30000;
const kibiBin = path.resolve(__dirname, "../../src/cli.ts");

function writeFiles(root: string, files: Record<string, string>): void {
  for (const [relativePath, content] of Object.entries(files)) {
    const absolutePath = path.join(root, relativePath);
    mkdirSync(path.dirname(absolutePath), { recursive: true });
    writeFileSync(absolutePath, content);
  }
}

function commitAll(cwd: string, message: string): void {
  execSync("git add -A", { cwd, stdio: "pipe" });
  execSync(`git commit -m "${message}" --no-verify`, { cwd, stdio: "pipe" });
}

function stagedCheck(cwd: string): { status: number | null; output: string } {
  const result = spawnSync("bun", [kibiBin, "check", "--staged"], {
    cwd,
    encoding: "utf8",
  });
  return {
    status: result.status,
    output: `${result.stdout ?? ""}${result.stderr ?? ""}`,
  };
}

const CLIENT = "export function fetchPets() {\n  return [];\n}\n";
const manifest = (kibi: unknown) =>
  JSON.stringify({ name: "sample", version: "1.0.0", private: true, kibi });

describe("kibi check --staged on generated source", () => {
  let tmpDir: string;

  beforeEach(() => {
    tmpDir = mkdtempSync(path.join(os.tmpdir(), "kibi-staged-generated-"));
    execSync("git init -b main", { cwd: tmpDir, stdio: "pipe" });
    execSync('git config user.email "test@example.com"', {
      cwd: tmpDir,
      stdio: "pipe",
    });
    execSync('git config user.name "Test User"', {
      cwd: tmpDir,
      stdio: "pipe",
    });
    execSync(`KB_PATH=.kb/branches/main bun ${kibiBin} init`, {
      cwd: tmpDir,
      stdio: "pipe",
    });
  });

  afterEach(() => {
    if (tmpDir && existsSync(tmpDir))
      rmSync(tmpDir, { recursive: true, force: true });
  });

  test(
    "needs requirement links for a generated file only when nothing committed marks it generated",
    () => {
      writeFiles(tmpDir, { "README.md": "# Sample\n" });
      commitAll(tmpDir, "initial");
      // Marking the file generated in the same change does not count.
      writeFiles(tmpDir, {
        ".gitattributes": "src/gen/** linguist-generated\n",
        "src/gen/client.ts": `// @generated by openapi-codegen\n${CLIENT}`,
      });
      execSync("git add -A", { cwd: tmpDir, stdio: "pipe" });
      const unmarked = stagedCheck(tmpDir);
      expect(unmarked.status).toBe(1);
      expect(unmarked.output).toContain("Traceability failed");
    },
    TEST_TIMEOUT_MS,
  );

  test(
    "skips the requirement-link check for symbols of a file .gitattributes marked generated",
    () => {
      writeFiles(tmpDir, {
        "README.md": "# Sample\n",
        ".gitattributes": "src/gen/** linguist-generated\n",
      });
      commitAll(tmpDir, "initial");
      writeFiles(tmpDir, { "src/gen/client.ts": CLIENT });
      execSync("git add -A", { cwd: tmpDir, stdio: "pipe" });
      const result = stagedCheck(tmpDir);
      expect(result.output).not.toContain("Traceability failed");
      expect(result.output).toContain(
        "Generated files: symbols without a requirement link in src/gen/client.ts are not checked for one",
      );
      expect(result.output).not.toContain("staged_file_ownership_missing");
      expect(result.status).toBe(0);
    },
    TEST_TIMEOUT_MS,
  );

  test(
    "reads kibi.generatedPaths, where a ! pattern keeps a file checked",
    () => {
      writeFiles(tmpDir, {
        "package.json": manifest({
          generatedPaths: ["src/gen/**", "!src/gen/hand.ts"],
        }),
      });
      commitAll(tmpDir, "initial");
      writeFiles(tmpDir, { "src/gen/client.ts": CLIENT });
      execSync("git add -A", { cwd: tmpDir, stdio: "pipe" });
      expect(stagedCheck(tmpDir).status).toBe(0);
      commitAll(tmpDir, "client");

      writeFiles(tmpDir, { "src/gen/hand.ts": CLIENT });
      execSync("git add -A", { cwd: tmpDir, stdio: "pipe" });
      const hand = stagedCheck(tmpDir);
      expect(hand.status).toBe(1);
      expect(hand.output).toContain("Traceability failed");
    },
    TEST_TIMEOUT_MS,
  );

  test(
    "trusts a generator header only when the committed file already carried it",
    () => {
      writeFiles(tmpDir, {
        "README.md": "# Sample\n",
        "src/parser.ts": `// Code generated by peggy. DO NOT EDIT.\n${CLIENT}`,
      });
      commitAll(tmpDir, "initial");
      writeFiles(tmpDir, {
        "src/parser.ts": `// Code generated by peggy. DO NOT EDIT.\n${CLIENT}export function parse() {\n  return 1;\n}\n`,
      });
      execSync("git add -A", { cwd: tmpDir, stdio: "pipe" });
      expect(stagedCheck(tmpDir).status).toBe(0);
    },
    TEST_TIMEOUT_MS,
  );

  test(
    "keeps checking a generated file that .kb/symbols.yaml names",
    () => {
      writeFiles(tmpDir, {
        ".gitattributes": "src/gen/** linguist-generated\n",
        ".kb/symbols.yaml":
          "symbols:\n  - id: SYM-fetch-pets\n    title: fetchPets\n    sourceFile: src/gen/client.ts\n    status: active\n",
        "src/gen/client.ts": CLIENT,
      });
      commitAll(tmpDir, "initial");
      execSync(`bun ${kibiBin} sync --refresh-symbol-coordinates`, {
        cwd: tmpDir,
        stdio: "pipe",
      });
      commitAll(tmpDir, "refresh symbols manifest");
      writeFiles(tmpDir, {
        "src/gen/client.ts": CLIENT.replace("[]", "[1]"),
      });
      execSync("git add -A", { cwd: tmpDir, stdio: "pipe" });
      const result = stagedCheck(tmpDir);
      expect(result.status).toBe(1);
      expect(result.output).toContain("Traceability failed");
      expect(result.output).not.toContain("Generated files:");
    },
    TEST_TIMEOUT_MS,
  );
});
