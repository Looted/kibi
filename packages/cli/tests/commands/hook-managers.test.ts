import { afterEach, beforeEach, describe, expect, test } from "bun:test";
import { spawnSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from "node:fs";
import * as path from "node:path";
import { parse as parseYaml } from "yaml";
import { doctorCommand } from "../../src/commands/doctor.js";
import {
  detectHookManager,
  hookManagerCommands,
  hookManagerCoverage,
  hookManagerSnippet,
  missingKibiHookCommands,
} from "../../src/commands/hook-managers.js";
import {
  MANAGED_HOOK_NAMES,
  hookDelegationSnippet,
} from "../../src/commands/init-helpers.js";
import { initCommand } from "../../src/commands/init.js";
import {
  captureIo,
  createGitWorkspace,
  git,
  isolateKibiEnv,
  removeTempDir,
  withCwd,
  writeHook,
} from "../helpers/in-process-workspace.js";

// executable_for TEST-git-hook-manager-integration
// Repositories whose hooks belong to lefthook, husky or the pre-commit
// framework: init leaves the hooks directory to the manager and prints its
// configuration, --print-hook emits every format from one command table, and
// doctor reads the manager configuration instead of generated hook runners.

interface DoctorCheck {
  name: string;
  passed: boolean;
  warning?: boolean;
  message: string;
  remediation?: string;
}

const LEFTHOOK_RUNNER =
  '#!/bin/sh\n# lefthook generated hook runner\ncall_lefthook run "$(basename "$0")" "$@"\n';

describe("existing git hook managers", () => {
  let restores: Array<() => void>;
  let roots: string[];

  beforeEach(() => {
    restores = [];
    roots = [];
    restores.push(isolateKibiEnv());
  });

  afterEach(() => {
    for (const restore of restores.reverse()) restore();
    for (const root of roots) removeTempDir(root);
  });

  function workspace(): string {
    const cwd = createGitWorkspace();
    roots.push(cwd);
    return cwd;
  }

  function hooksDir(cwd: string): string {
    return path.join(cwd, ".git", "hooks");
  }

  async function init(cwd: string) {
    const io = captureIo();
    restores.push(io.restore);
    const result = await withCwd(cwd, () => initCommand({ hooks: true }));
    return { result, io };
  }

  async function printHook(hook: string, format?: string) {
    const io = captureIo({ stdio: true });
    try {
      const result = await initCommand({ printHook: hook, format });
      return { result, out: io.stdout.join(""), err: io.errorText() };
    } finally {
      io.restore();
    }
  }

  async function doctorChecks(cwd: string): Promise<DoctorCheck[]> {
    const io = captureIo();
    restores.push(io.restore);
    await withCwd(cwd, () => doctorCommand({ format: "json" }));
    const parsed = JSON.parse(io.logs[0] ?? "{}") as { checks: DoctorCheck[] };
    return parsed.checks.filter((check) =>
      ["Git hooks", "pre-commit hook", "post-rewrite hook"].includes(
        check.name,
      ),
    );
  }

  describe("detection", () => {
    test("finds lefthook from its config file before it is installed", () => {
      const cwd = workspace();
      writeFileSync(path.join(cwd, "lefthook.yml"), "pre-commit: {}\n");
      expect(detectHookManager(cwd, hooksDir(cwd))).toEqual({
        name: "lefthook",
        configPath: "lefthook.yml",
      });
    });

    test("finds lefthook and pre-commit from the hook runners they generate", () => {
      const cwd = workspace();
      writeHook(cwd, "pre-commit", LEFTHOOK_RUNNER);
      expect(detectHookManager(cwd, hooksDir(cwd))?.name).toBe("lefthook");

      const other = workspace();
      writeHook(
        other,
        "pre-commit",
        "#!/usr/bin/env bash\n# File generated by pre-commit: https://pre-commit.com\n",
      );
      expect(detectHookManager(other, hooksDir(other))).toEqual({
        name: "pre-commit",
        configPath: ".pre-commit-config.yaml",
      });
    });

    test("finds husky from core.hooksPath or its directory, never from hook text", () => {
      const cwd = workspace();
      expect(
        detectHookManager(cwd, path.join(cwd, ".husky", "_"), ".husky/_"),
      ).toEqual({ name: "husky", configPath: ".husky" });

      // A hand-written hook that sources an old husky helper is still the
      // project's own hook, diagnosed as a custom hook.
      const plain = workspace();
      writeHook(
        plain,
        "pre-commit",
        '#!/bin/sh\n. "$(dirname "$0")/_/husky.sh"\nkibi check --staged\n',
      );
      expect(detectHookManager(plain, hooksDir(plain))).toBeNull();

      mkdirSync(path.join(plain, ".husky"));
      expect(detectHookManager(plain, hooksDir(plain))?.name).toBe("husky");
    });

    test("reports no manager for a plain repository", () => {
      const cwd = workspace();
      expect(detectHookManager(cwd, hooksDir(cwd))).toBeNull();
    });
  });

  describe("--print-hook formats", () => {
    test("shell output for one hook is unchanged and 'all' prints every hook", async () => {
      const single = await printHook("pre-commit");
      expect(single.result.exitCode).toBe(0);
      expect(single.out).toBe(hookDelegationSnippet("pre-commit"));

      const all = await printHook("all");
      for (const hook of MANAGED_HOOK_NAMES) {
        expect(all.out).toContain(hookDelegationSnippet(hook));
      }
      // The commit gate comes first.
      expect(all.out.indexOf("pre-commit")).toBeLessThan(
        all.out.indexOf("post-checkout"),
      );
    });

    test("rejects an unknown format and --format without --print-hook", async () => {
      const bad = await printHook("pre-commit", "simple-git-hooks");
      expect(bad.result.exitCode).toBe(1);
      expect(bad.err).toContain(
        "unknown --format 'simple-git-hooks' for --print-hook. Expected one of: shell, lefthook, husky, pre-commit.",
      );

      const io = captureIo();
      restores.push(io.restore);
      const orphan = await initCommand({ format: "lefthook" });
      expect(orphan.exitCode).toBe(1);
      expect(io.errorText()).toContain("--format applies only to --print-hook");
    });

    test("lefthook and pre-commit output is valid config that covers every Kibi command", async () => {
      for (const format of ["lefthook", "pre-commit"] as const) {
        const cwd = workspace();
        const { out } = await printHook("all", format);
        // Parses as YAML: the printed text can be merged as-is.
        expect(() => parseYaml(out)).not.toThrow();
        writeFileSync(
          path.join(
            cwd,
            format === "lefthook" ? "lefthook.yml" : ".pre-commit-config.yaml",
          ),
          out,
        );
        for (const entry of hookManagerCoverage(format, cwd)) {
          expect(entry).toEqual({
            hook: entry.hook,
            configured: true,
            missing: [],
          });
        }
      }
    });

    test("husky output is one hook script per .husky file", async () => {
      const cwd = workspace();
      const { out } = await printHook("all", "husky");
      mkdirSync(path.join(cwd, ".husky"));
      for (const section of out.split(/^# --- \.husky\//m).slice(1)) {
        const hook = section.slice(0, section.indexOf(" ---"));
        writeFileSync(
          path.join(cwd, ".husky", hook),
          section.slice(section.indexOf("\n") + 1),
        );
      }
      expect(readdirSync(path.join(cwd, ".husky")).sort()).toEqual(
        [...MANAGED_HOOK_NAMES].sort(),
      );
      for (const entry of hookManagerCoverage("husky", cwd)) {
        expect(entry.missing).toEqual([]);
      }
    });

    test("printed lefthook and pre-commit commands sync only on branch checkouts and rebases", async () => {
      const cwd = workspace();
      const bin = path.join(cwd, "bin");
      mkdirSync(bin);
      const calls = path.join(cwd, "calls.log");
      // A stand-in npx that records the kibi command it was asked to run.
      writeFileSync(
        path.join(bin, "npx"),
        `#!/bin/sh\necho "$*" >> "${calls}"\n`,
        { mode: 0o755 },
      );
      const run = (command: string, env: Record<string, string> = {}) =>
        spawnSync("sh", ["-c", command], {
          cwd,
          stdio: "ignore",
          env: { ...process.env, ...env, PATH: `${bin}:/usr/bin:/bin` },
        }).status;
      const lefthook = parseYaml((await printHook("all", "lefthook")).out);
      const lefthookRun = (hook: string): string =>
        lefthook[hook].commands[
          hook === "pre-commit" ? "kibi-check" : "kibi-sync"
        ].run;

      expect(run(lefthookRun("post-checkout").replace("{3}", "0"))).toBe(0);
      expect(run(lefthookRun("post-rewrite").replace("{1}", "amend"))).toBe(0);
      expect(existsSync(calls)).toBe(false);
      expect(run(lefthookRun("post-checkout").replace("{3}", "1"))).toBe(0);
      expect(run(lefthookRun("post-rewrite").replace("{1}", "rebase"))).toBe(0);
      expect(run(lefthookRun("pre-commit"))).toBe(0);

      const preCommit = parseYaml((await printHook("all", "pre-commit")).out);
      const entry = (id: string): string =>
        preCommit.repos[0].hooks.find((hook: { id: string }) => hook.id === id)
          .entry;
      // The pre-commit framework runs `entry` through a shell-word split; the
      // `sh -c '…'` entries hold a single quoted script.
      const script = (id: string) =>
        entry(id)
          .replace(/^sh -c '/, "")
          .replace(/'$/, "");
      expect(
        run(script("kibi-sync-checkout"), { PRE_COMMIT_CHECKOUT_TYPE: "0" }),
      ).toBe(0);
      expect(
        run(script("kibi-sync-rebase"), {
          PRE_COMMIT_REWRITE_COMMAND: "amend",
        }),
      ).toBe(0);
      expect(
        run(script("kibi-sync-checkout"), { PRE_COMMIT_CHECKOUT_TYPE: "1" }),
      ).toBe(0);
      expect(
        run(script("kibi-sync-rebase"), {
          PRE_COMMIT_REWRITE_COMMAND: "rebase",
        }),
      ).toBe(0);

      expect(readFileSync(calls, "utf8")).toBe(
        [
          "--no-install kibi sync",
          "--no-install kibi sync",
          "--no-install kibi check-generated --staged --changed-only",
          "--no-install kibi check --staged",
          "--no-install kibi sync",
          "--no-install kibi sync",
          "",
        ].join("\n"),
      );
    });
  });

  describe("reading manager configuration", () => {
    test("collects lefthook commands, nested job groups, scripts and local overrides", () => {
      const cwd = workspace();
      writeFileSync(
        path.join(cwd, "lefthook.yml"),
        [
          "pre-commit:",
          "  jobs:",
          "    - run: npm run lint",
          "    - group:",
          "        jobs:",
          "          - run: npx kibi check --staged",
          "post-merge:",
          "  scripts:",
          '    "sync.sh":',
          "      runner: sh",
          "",
        ].join("\n"),
      );
      writeFileSync(
        path.join(cwd, "lefthook-local.yml"),
        "pre-commit:\n  commands:\n    gen:\n      run: kibi check-generated --staged --changed-only\n",
      );
      mkdirSync(path.join(cwd, ".lefthook", "post-merge"), { recursive: true });
      writeFileSync(
        path.join(cwd, ".lefthook", "post-merge", "sync.sh"),
        "#!/bin/sh\nnode_modules/.bin/kibi sync\n",
      );

      expect(
        missingKibiHookCommands(
          "pre-commit",
          hookManagerCommands("lefthook", cwd, "pre-commit") ?? [],
        ),
      ).toEqual([]);
      expect(
        missingKibiHookCommands(
          "post-merge",
          hookManagerCommands("lefthook", cwd, "post-merge") ?? [],
        ),
      ).toEqual([]);
      expect(hookManagerCommands("lefthook", cwd, "post-checkout")).toBeNull();
    });

    test("maps pre-commit framework stages, including pre-3.2 names and defaults", () => {
      const cwd = workspace();
      writeFileSync(
        path.join(cwd, ".pre-commit-config.yaml"),
        [
          "repos:",
          "  - repo: local",
          "    hooks:",
          "      - id: gen",
          "        entry: kibi check-generated",
          "        args: [--staged, --changed-only]",
          "        language: system",
          "      - id: check",
          "        entry: kibi check --staged",
          "        language: system",
          "        stages: [commit]",
          "      - id: sync",
          "        entry: kibi sync",
          "        language: system",
          "        stages: [post-merge]",
          "",
        ].join("\n"),
      );
      expect(
        missingKibiHookCommands(
          "pre-commit",
          hookManagerCommands("pre-commit", cwd, "pre-commit") ?? [],
        ),
      ).toEqual([]);
      expect(hookManagerCommands("pre-commit", cwd, "post-merge")).toEqual([
        "kibi sync",
      ]);
      expect(hookManagerCommands("pre-commit", cwd, "post-rewrite")).toBeNull();
    });
  });

  describe("kibi init", () => {
    test("installs nothing under lefthook and prints the missing configuration", async () => {
      const cwd = workspace();
      writeFileSync(
        path.join(cwd, "lefthook.yml"),
        "pre-commit:\n  commands:\n    lint:\n      run: npm run lint\n",
      );
      writeHook(cwd, "pre-commit", LEFTHOOK_RUNNER);

      const { result, io } = await init(cwd);
      expect(result.exitCode).toBe(0);
      // The manager's runner is untouched and no Kibi hook was added.
      expect(readFileSync(path.join(hooksDir(cwd), "pre-commit"), "utf8")).toBe(
        LEFTHOOK_RUNNER,
      );
      expect(readdirSync(hooksDir(cwd))).toEqual(["pre-commit"]);
      const text = io.logText();
      expect(text).toContain(
        "! Git hooks are managed by lefthook (lefthook.yml); Kibi installed no hooks of its own. lefthook.yml does not visibly run Kibi's commands for: pre-commit, post-checkout, post-merge, post-rewrite.",
      );
      expect(text).toContain(
        hookManagerSnippet("lefthook", MANAGED_HOOK_NAMES),
      );
      expect(text).toContain(
        "Print it again with: kibi init --print-hook all --format lefthook",
      );
      expect(text).not.toContain("Installed/updated Kibi git hooks");
    });

    test("confirms a lefthook config that already runs every Kibi command", async () => {
      const cwd = workspace();
      writeFileSync(
        path.join(cwd, "lefthook.yml"),
        hookManagerSnippet("lefthook", MANAGED_HOOK_NAMES),
      );
      const { io } = await init(cwd);
      expect(io.logText()).toContain(
        "✓ Git hooks are managed by lefthook (lefthook.yml), which already runs Kibi's hook commands; Kibi installed no hooks of its own.",
      );
      expect(existsSync(path.join(hooksDir(cwd), "pre-commit"))).toBe(false);
    });

    test("names only the hooks husky does not cover", async () => {
      const cwd = workspace();
      mkdirSync(path.join(cwd, ".husky", "_"), { recursive: true });
      git(cwd, "config core.hooksPath .husky/_");
      writeFileSync(
        path.join(cwd, ".husky", "pre-commit"),
        `npm test\n${hookDelegationSnippet("pre-commit")}`,
      );
      const { io } = await init(cwd);
      const text = io.logText();
      expect(text).toContain(
        "! Git hooks are managed by husky (.husky); Kibi installed no hooks of its own. .husky does not visibly run Kibi's commands for: post-checkout, post-merge, post-rewrite.",
      );
      expect(text).toContain("# --- .husky/post-checkout ---");
      expect(text).not.toContain("# --- .husky/pre-commit ---");
      expect(readdirSync(path.join(cwd, ".husky", "_"))).toEqual([]);
    });
  });

  describe("kibi doctor", () => {
    test("passes lefthook hooks that run Kibi's commands", async () => {
      const cwd = workspace();
      writeFileSync(
        path.join(cwd, "lefthook.yml"),
        hookManagerSnippet("lefthook", MANAGED_HOOK_NAMES),
      );
      for (const hook of MANAGED_HOOK_NAMES)
        writeHook(cwd, hook, LEFTHOOK_RUNNER);

      const checks = await doctorChecks(cwd);
      expect(
        checks.map(({ name, passed, warning, message }) => ({
          name,
          passed,
          warning,
          message,
        })),
      ).toEqual([
        {
          name: "Git hooks",
          passed: true,
          warning: undefined,
          message:
            "Managed by lefthook (lefthook.yml); post-checkout runs 'kibi sync'; post-merge runs 'kibi sync'",
        },
        {
          name: "pre-commit hook",
          passed: true,
          warning: undefined,
          message:
            "Managed by lefthook (lefthook.yml); pre-commit runs 'kibi check-generated --staged --changed-only' and 'kibi check --staged'",
        },
        {
          name: "post-rewrite hook",
          passed: true,
          warning: undefined,
          message:
            "Managed by lefthook (lefthook.yml); post-rewrite runs 'kibi sync'",
        },
      ]);
    });

    test("warns, without failing, when lefthook reaches Kibi through a task runner it cannot read", async () => {
      const cwd = workspace();
      writeFileSync(
        path.join(cwd, "lefthook.yml"),
        "pre-commit:\n  commands:\n    check:\n      run: task check:commit\n",
      );
      writeHook(cwd, "pre-commit", LEFTHOOK_RUNNER);

      const preCommit = (await doctorChecks(cwd)).find(
        (check) => check.name === "pre-commit hook",
      );
      expect(preCommit).toEqual({
        name: "pre-commit hook",
        passed: true,
        warning: true,
        message:
          "Managed by lefthook (lefthook.yml); pre-commit does not visibly run 'kibi check-generated --staged --changed-only' and 'kibi check --staged'. Kibi reads only the lefthook configuration, not the task runners or scripts it calls; unless they run these commands, commits skip Kibi enforcement",
        remediation:
          "Add Kibi's commands to lefthook.yml. Print them with: kibi init --print-hook pre-commit --format lefthook",
      });
    });
  });
});
