describe("pre-commit framework configuration", () => {
  const configure = (yaml: string) => put(".pre-commit-config.yaml", yaml);

  test("is not configured without a file, a mapping or a repos list", () => {
    expect(hookManagerCommands("pre-commit", root, "pre-commit")).toBeNull();
    configure("- repos\n");
    expect(hookManagerCommands("pre-commit", root, "pre-commit")).toBeNull();
    configure("default_stages: [pre-commit]\n");
    expect(hookManagerCommands("pre-commit", root, "pre-commit")).toBeNull();
    configure("repos: {}\n");
    expect(hookManagerCommands("pre-commit", root, "pre-commit")).toBeNull();
    configure("repos: [unclosed\n");
    expect(hookManagerCommands("pre-commit", root, "pre-commit")).toBeNull();
  });

  test("skips malformed repos and hook entries", () => {
    configure(
      [
        "repos:",
        "  - null",
        "  - repo: local",
        "  - repo: local",
        "    hooks: {}",
        "  - repo: local",
        "    hooks:",
        "      - null",
        "      - [entry, 'kibi check --staged']",
        "      - just a string",
        "",
      ].join("\n"),
    );
    expect(hookManagerCommands("pre-commit", root, "pre-commit")).toBeNull();
  });

  test("runs hooks without stages only at pre-commit", () => {
    configure(
      "repos:\n  - repo: local\n    hooks:\n      - id: a\n        entry: kibi check --staged\n",
    );
    expect(hookManagerCommands("pre-commit", root, "pre-commit")).toEqual([
      "kibi check --staged",
    ]);
    expect(hookManagerCommands("pre-commit", root, "post-merge")).toBeNull();
  });

  test("selects hooks by stage, legacy stage and default stages", () => {
    configure(
      [
        "default_stages: [post-merge]",
        "repos:",
        "  - repo: local",
        "    hooks:",
        "      - id: default",
        "        entry: default-stage",
        "      - id: legacy",
        "        entry: legacy-stage",
        "        stages: [commit]",
        "      - id: mixed",
        "        entry: mixed-stage",
        "        stages: [pre-push, pre-commit]",
        "      - id: nested",
        "        entry: nested-stage",
        "        stages: [[commit], [pre-commit], 7]",
        "      - id: push",
        "        entry: push-stage",
        "        stages: [push, merge-commit]",
        "      - id: scalar",
        "        entry: scalar-stage",
        "        stages: pre-commit",
        "",
      ].join("\n"),
    );
    expect(hookManagerCommands("pre-commit", root, "pre-commit")).toEqual([
      "legacy-stage",
      "mixed-stage",
    ]);
    expect(hookManagerCommands("pre-commit", root, "post-merge")).toEqual([
      "default-stage",
      "scalar-stage",
    ]);
    expect(hookManagerCommands("pre-commit", root, "post-rewrite")).toBeNull();
  });

  test("ignores a default_stages value that is not a list", () => {
    configure(
      "default_stages: post-merge\nrepos:\n  - hooks:\n      - entry: x\n",
    );
    expect(hookManagerCommands("pre-commit", root, "pre-commit")).toEqual([
      "x",
    ]);
  });

  test("joins string args to the entry and counts remote hooks as opaque", () => {
    configure(
      [
        "repos:",
        "  - repo: https://example.invalid/hooks",
        "    hooks:",
        "      - id: remote",
        "        args: [kibi, check, --staged]",
        "      - id: number",
        "        entry: 5",
        "  - repo: local",
        "    hooks:",
        "      - id: args",
        "        entry: kibi check",
        "        args: [--staged, [--changed-only], 3]",
        "      - id: scalar-args",
        "        entry: kibi sync",
        "        args: --staged",
        "",
      ].join("\n"),
    );
    expect(hookManagerCommands("pre-commit", root, "pre-commit")).toEqual([
      "kibi check --staged",
      "kibi sync",
    ]);
  });
});

describe("missingKibiHookCommands", () => {
  const missing = (hook: ManagedHookName, ...scripts: string[]) =>
    missingKibiHookCommands(hook, scripts);

  test("reports every command for an empty definition", () => {
    expect(missing("pre-commit")).toEqual(CHECK_LABELS);
    expect(missing("post-merge")).toEqual(["kibi sync"]);
    expect(missing("post-checkout", "")).toEqual(["kibi sync"]);
    expect(missing("post-rewrite", "echo sync")).toEqual(["kibi sync"]);
  });

  test("accepts each spelling of the kibi binary", () => {
    for (const command of [
      "kibi sync",
      "npx --no-install kibi sync",
      "node_modules/.bin/kibi sync --quiet",
      '"$KIBI_BIN" sync',
      "${KIBI_BIN} sync",
      "sh -c 'kibi sync'",
    ]) {
      expect(missing("post-merge", command)).toEqual([]);
    }
  });

  test("rejects other subcommands and binaries", () => {
    for (const command of [
      "kibi syncs",
      "kibi-sync",
      "mykibi sync",
      "kibi",
      "sync",
      "kibi status sync",
    ]) {
      expect(missing("post-merge", command)).toEqual(["kibi sync"]);
    }
  });

  test("ignores comment lines, including indented ones", () => {
    expect(missing("post-merge", "# kibi sync")).toEqual(["kibi sync"]);
    expect(missing("post-merge", "   # kibi sync\necho")).toEqual([
      "kibi sync",
    ]);
    expect(missing("post-merge", "kibi sync #")).toEqual([]);
    expect(missing("post-merge", "echo\nkibi sync # sync it")).toEqual([]);
  });

  test("splits commands on shell separators", () => {
    for (const separator of ["&&", "||", ";", "|"]) {
      expect(
        missing("pre-commit", `kibi check ${separator} echo --staged`),
      ).toEqual(CHECK_LABELS);
    }
    expect(
      missing(
        "pre-commit",
        "kibi check-generated --staged && echo --changed-only",
      ),
    ).toEqual(CHECK_LABELS);
    expect(
      missing(
        "pre-commit",
        "kibi check-generated --staged --changed-only&&kibi check --staged",
      ),
    ).toEqual([]);
  });

  test("needs both flags on check-generated", () => {
    expect(missing("pre-commit", "kibi check --staged")).toEqual([
      CHECK_LABELS[0],
    ]);
    expect(
      missing(
        "pre-commit",
        "kibi check-generated --staged",
        "kibi check --staged",
      ),
    ).toEqual([CHECK_LABELS[0]]);
    expect(
      missing(
        "pre-commit",
        "kibi check-generated --changed-only",
        "kibi check --staged",
      ),
    ).toEqual([CHECK_LABELS[0]]);
    expect(
      missing(
        "pre-commit",
        "echo --staged --changed-only",
        "kibi check --staged",
      ),
    ).toEqual([CHECK_LABELS[0]]);
    expect(
      missing(
        "pre-commit",
        "sh -c 'kibi check-generated --changed-only --staged'",
      ),
    ).toEqual([CHECK_LABELS[1]]);
  });

  test("needs --staged on check", () => {
    expect(missing("pre-commit", "kibi check")).toEqual(CHECK_LABELS);
    expect(missing("pre-commit", "echo --staged")).toEqual(CHECK_LABELS);
    expect(missing("pre-commit", "kibi check --stagedx")).toEqual(CHECK_LABELS);
    expect(missing("pre-commit", "kibi check x--staged")).toEqual(CHECK_LABELS);
    expect(missing("pre-commit", 'kibi check "--staged"')).toEqual(
      CHECK_LABELS,
    );
    expect(missing("pre-commit", "kibi check --staged'")).toEqual([
      CHECK_LABELS[0],
    ]);
  });
});

describe("hookManagerCoverage", () => {
  test("lists every hook in print order with what it misses", () => {
    put(
      "lefthook.yml",
      [
        "pre-commit:",
        "  commands:",
        "    check:",
        "      run: kibi check --staged",
        "post-merge:",
        "  commands:",
        "    sync:",
        "      run: kibi sync",
        "post-rewrite:",
        "  commands: {}",
        "",
      ].join("\n"),
    );
    expect(hookManagerCoverage("lefthook", root)).toEqual([
      { hook: "pre-commit", configured: true, missing: [CHECK_LABELS[0]] },
      { hook: "post-checkout", configured: false, missing: ["kibi sync"] },
      { hook: "post-merge", configured: true, missing: [] },
      { hook: "post-rewrite", configured: true, missing: ["kibi sync"] },
    ]);
  });

  test("reports every command of an unconfigured hook", () => {
    expect(hookManagerCoverage("husky", root)).toEqual([
      { hook: "pre-commit", configured: false, missing: CHECK_LABELS },
      { hook: "post-checkout", configured: false, missing: ["kibi sync"] },
      { hook: "post-merge", configured: false, missing: ["kibi sync"] },
      { hook: "post-rewrite", configured: false, missing: ["kibi sync"] },
    ]);
  });
});

