describe("long cells wrap instead of being cut", () => {
  const long = "word ".repeat(20).trim();

  test("in every discovery table", () => {
    for (const payload of [
      { count: 1, results: [{ snippet: long, entity: {} }] },
      { branch: "main", syncState: "fresh", kbPath: long },
      { count: 1, rows: [{ source: long }] },
      { nodes: [{ title: long }], edges: [] },
      { nodes: [], edges: [{ from: long }] },
    ]) {
      const text = render(payload) ?? "";
      expect(text).not.toContain("…");
      expect(text.split("word").length - 1).toBe(20);
    }
  });

  test("in the plan tables", () => {
    for (const payload of [
      { repairPlan: { version: "v1", planId: long } },
      { repairPlan: { version: "v1", batches: [{ requirementId: long }] } },
      { legacyMigrationPlan: { version: "v1", planId: long } },
    ]) {
      const text = coverage({ summary: {}, rows: [], ...payload });
      expect(text).not.toContain("…");
      expect(text.split("word").length - 1).toBe(20);
    }
  });

  test("labels grouped link metrics as traceability by default", () => {
    const text = coverage({ summary: { total: 1, proofTested: 1 }, rows: [] });
    expect(text).toContain("│ Traceability (links)   │");
    expect(text).toContain("│ Proof (evidence)       │");
    expect(text).toContain("│   total                │ 1");
  });
});
