import { afterEach, describe, expect, it } from "bun:test";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import {
  generatedClassifier,
  generatedSourceFiles,
  gitAttributeVerdicts,
  hasGeneratedHeader,
  isGeneratedSource,
  kbReferencedFiles,
  stagedGeneratedPaths,
} from "../../src/plugins/generated-sources.js";

const roots: string[] = [];
const savedPath = process.env.PATH;
afterEach(() => {
  process.env.PATH = savedPath;
  for (const root of roots.splice(0))
    fs.rmSync(root, { recursive: true, force: true });
});

function workspace(files: Record<string, string>): string {
  const root = fs.mkdtempSync(path.join(tmpdir(), "kibi-generated-"));
  roots.push(root);
  for (const [relative, content] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(root, relative)), { recursive: true });
    fs.writeFileSync(path.join(root, relative), content);
  }
  return root;
}

function git(root: string, ...args: string[]): void {
  execFileSync("git", args, {
    cwd: root,
    stdio: "ignore",
    env: {
      ...process.env,
      GIT_AUTHOR_NAME: "t",
      GIT_AUTHOR_EMAIL: "t@example.com",
      GIT_COMMITTER_NAME: "t",
      GIT_COMMITTER_EMAIL: "t@example.com",
    },
  });
}

/** Put a `git` first on PATH that logs each call and runs the real git. */
function countGitCalls(): () => number {
  const realGit = execFileSync("sh", ["-c", "command -v git"], {
    encoding: "utf8",
  }).trim();
  const directory = fs.mkdtempSync(path.join(tmpdir(), "kibi-fake-git-"));
  roots.push(directory);
  const log = path.join(directory, "calls.log");
  fs.writeFileSync(
    path.join(directory, "git"),
    `#!/bin/sh\necho call >> '${log}'\nexec '${realGit}' "$@"\n`,
    { mode: 0o755 },
  );
  process.env.PATH = `${directory}${path.delimiter}${savedPath}`;
  return () =>
    fs.existsSync(log)
      ? fs.readFileSync(log, "utf8").split("\n").filter(Boolean).length
      : 0;
}

const ATTRIBUTES = [
  "set/** linguist-generated",
  "true/** linguist-generated=true",
  "unset/** -linguist-generated",
  "false/** linguist-generated=false",
  "both/** linguist-generated -linguist-vendored",
  "vendor/** linguist-vendored",
  "",
].join("\n");

describe("generator headers", () => {
  it("reads the markers in the first five lines and first kilobyte only", () => {
    expect(hasGeneratedHeader("// autogenerated by tool\n")).toBe(true);
    expect(hasGeneratedHeader("// auto-generated by tool\n")).toBe(true);
    expect(hasGeneratedHeader("# This file was generated by protoc\n")).toBe(
      true,
    );
    expect(hasGeneratedHeader("# this file has been generated\n")).toBe(true);
    expect(hasGeneratedHeader("// @generated\n")).toBe(true);
    // Past the first kilobyte, even on the first line, a marker is prose.
    expect(hasGeneratedHeader(`${"x".repeat(1100)} DO NOT EDIT\n`)).toBe(false);
    // Lines are not glued together into a marker.
    expect(hasGeneratedHeader("// auto-\ngenerated later\n")).toBe(false);
    expect(hasGeneratedHeader("int main(void) { return 0; }\n")).toBe(false);
    expect(hasGeneratedHeader(undefined)).toBe(false);
  });
});

describe("git attribute verdicts", () => {
  it("reads set, true, unset and false for linguist-generated and linguist-vendored", () => {
    const root = workspace({ ".gitattributes": ATTRIBUTES });
    git(root, "init", "-q");
    const verdicts = gitAttributeVerdicts(root, [
      "set/a.go",
      "true/a.go",
      "unset/a.go",
      "false/a.go",
      "both/a.go",
      "vendor/a.go",
      "plain/a.go",
      "set/two words.go",
    ]);
    expect(Object.fromEntries(verdicts)).toEqual({
      "set/a.go": true,
      "true/a.go": true,
      "unset/a.go": false,
      "false/a.go": false,
      "both/a.go": true,
      "vendor/a.go": true,
      "set/two words.go": true,
    });
  });

  it("does not run git for no files", () => {
    const calls = countGitCalls();
    expect(gitAttributeVerdicts(tmpdir(), []).size).toBe(0);
    expect(calls()).toBe(0);
  });

  it("reads .gitattributes from the given tree instead of the working tree", () => {
    const root = workspace({ ".gitattributes": "gen/** linguist-generated\n" });
    git(root, "init", "-q");
    git(root, "add", "-A");
    git(root, "commit", "-q", "-m", "base");
    fs.writeFileSync(
      path.join(root, ".gitattributes"),
      "other/** linguist-generated\n",
    );
    expect(
      Object.fromEntries(
        gitAttributeVerdicts(root, ["gen/a.go", "other/b.go"], "HEAD"),
      ),
    ).toEqual({ "gen/a.go": true });
    expect(
      Object.fromEntries(
        gitAttributeVerdicts(root, ["gen/a.go", "other/b.go"]),
      ),
    ).toEqual({ "other/b.go": true });
  });
});

describe("the generated-file classifier", () => {
  it("asks git once for each path it was not given up front", () => {
    const root = workspace({ ".gitattributes": ATTRIBUTES });
    git(root, "init", "-q");
    const calls = countGitCalls();
    const generated = generatedClassifier(root, ["plain/a.go"]);
    expect(calls()).toBe(1);
    expect(generated("plain/a.go", () => "package a\n")).toBe(false);
    expect(generated("set/b.go", () => "package b\n")).toBe(true);
    expect(generated("set/b.go", () => "package b\n")).toBe(true);
    expect(
      generated("false/c.go", () => "// Code generated. DO NOT EDIT.\n"),
    ).toBe(false);
    expect(generated("plain/d.go", () => "// DO NOT EDIT\n")).toBe(true);
    expect(calls()).toBe(4);
  });

  it("lets a pattern decide without asking git, and a ! pattern mark a file hand-written", () => {
    const root = workspace({ ".gitattributes": ATTRIBUTES });
    git(root, "init", "-q");
    const calls = countGitCalls();
    const options = { patterns: ["gen/**", "!gen/keep.go"] };
    expect(isGeneratedSource(root, "gen/a.go", "package a\n", options)).toBe(
      true,
    );
    expect(
      isGeneratedSource(root, "gen/keep.go", "// DO NOT EDIT\n", options),
    ).toBe(false);
    expect(calls()).toBe(0);
    expect(isGeneratedSource(root, "set/b.go", "package b\n", options)).toBe(
      true,
    );
    expect(isGeneratedSource(root, "plain/c.go", "package c\n")).toBe(false);
    expect(calls()).toBe(2);
  });

  it("reads the head of each listed file, skips unreadable ones and leaks no descriptors", () => {
    const files: Record<string, string> = {
      "hdr/a.go": "// Code generated by x. DO NOT EDIT.\npackage a\n",
      "hand/b.go": "package b\n",
    };
    for (let index = 0; index < 40; index += 1)
      files[`many/f${index}.go`] = "package many\n";
    const root = workspace(files);
    fs.mkdirSync(path.join(root, "dir.go"));
    const listed = [...Object.keys(files), "missing/c.go", "dir.go"];
    const openDescriptors = () =>
      fs.existsSync("/proc/self/fd")
        ? fs.readdirSync("/proc/self/fd").length
        : 0;
    const before = openDescriptors();
    expect([...generatedSourceFiles(root, listed)]).toEqual(["hdr/a.go"]);
    expect(openDescriptors() - before).toBeLessThan(20);
    expect([
      ...generatedSourceFiles(root, listed, { patterns: ["hand/"] }),
    ]).toEqual(["hdr/a.go", "hand/b.go"]);
  });

  it("judges staged files by the base tree's attributes and their committed text", () => {
    const root = workspace({ ".gitattributes": "gen/** linguist-generated\n" });
    git(root, "init", "-q");
    git(root, "add", "-A");
    git(root, "commit", "-q", "-m", "base");
    fs.writeFileSync(
      path.join(root, ".gitattributes"),
      "other/** linguist-generated\n",
    );
    const inventory = [
      { path: "gen/a.go" },
      { path: "other/b.go" },
      {
        path: "hdr/c.go",
        previousContent: "// Code generated by x. DO NOT EDIT.\n",
      },
      { path: "hand/d.go", previousContent: "package d\n" },
      { path: "new/e.go" },
      { path: "pat/f.go" },
    ];
    const calls = countGitCalls();
    expect([
      ...stagedGeneratedPaths(root, inventory, ["pat/"], "HEAD"),
    ]).toEqual(["gen/a.go", "hdr/c.go", "pat/f.go"]);
    // One git call reads the attributes of every staged path up front.
    expect(calls()).toBe(1);
    expect([
      ...stagedGeneratedPaths(root, inventory, undefined, "HEAD"),
    ]).toEqual(["gen/a.go", "hdr/c.go"]);
  });
});

describe("generated files the KB names", () => {
  it("finds each candidate in any readable KB file", () => {
    const root = workspace({
      ".kb/one.yaml": "sourceFile: gen/a.go\n",
      ".kb/two.yaml": "files:\n  - gen/b.go\n",
    });
    expect([
      ...kbReferencedFiles(
        root,
        [".kb/missing.yaml", ".kb/one.yaml", ".kb/two.yaml"],
        ["gen/a.go", "gen/b.go", "gen/c.go"],
      ),
    ]).toEqual(["gen/a.go", "gen/b.go"]);
    expect(kbReferencedFiles(root, [".kb/one.yaml"], []).size).toBe(0);
  });

  it("counts a whole path only, not one inside a longer path", () => {
    const named = (text: string) => {
      const root = workspace({ ".kb/x.md": text });
      return kbReferencedFiles(root, [".kb/x.md"], ["gen/a.go"]).has(
        "gen/a.go",
      );
    };
    expect(named("gen/a.go")).toBe(true);
    expect(named("see gen/a.go")).toBe(true);
    expect(named("see gen/a.go here")).toBe(true);
    expect(named("see gen/a.go.")).toBe(true);
    expect(named("see gen/a.go. Next")).toBe(true);
    expect(named("(gen/a.go)")).toBe(true);
    expect(named(".x gen/a.go")).toBe(true);
    expect(named("gen/a.go.bak")).toBe(false);
    expect(named("gen/a.goX")).toBe(false);
    expect(named("gen/a.go/x")).toBe(false);
    expect(named("gen/a.go-x")).toBe(false);
    expect(named("gen/a.go_1")).toBe(false);
    expect(named("xgen/a.go")).toBe(false);
    expect(named("src/gen/a.go")).toBe(false);
    expect(named("-gen/a.go")).toBe(false);
    expect(named(".gen/a.go")).toBe(false);
    expect(named("gen/a.go.bak and gen/a.go")).toBe(true);
  });
});
