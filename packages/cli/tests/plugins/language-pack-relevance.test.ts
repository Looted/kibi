const roots: string[] = [];
afterEach(() => {
  for (const root of roots.splice(0))
    fs.rmSync(root, { recursive: true, force: true });
});

function workspace(files: Record<string, string>): string {
  const root = fs.mkdtempSync(path.join(tmpdir(), "kibi-pack-relevance-"));
  roots.push(root);
  for (const [relative, content] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(root, relative)), { recursive: true });
    fs.writeFileSync(path.join(root, relative), content);
  }
  return root;
}

function git(root: string, ...args: string[]): void {
  execFileSync("git", args, {
    cwd: root,
    stdio: "ignore",
    env: {
      ...process.env,
      GIT_AUTHOR_NAME: "t",
      GIT_AUTHOR_EMAIL: "t@example.com",
      GIT_COMMITTER_NAME: "t",
      GIT_COMMITTER_EMAIL: "t@example.com",
    },
  });
}

function gitTrack(root: string): void {
  git(root, "init", "-q");
  git(root, "add", "-A");
}

const symbolsOnly = {
  plugins: [
    {
      package: "kibi-plugin-treesitter",
      capabilities: { "kibi.symbol-extractor.v2": { mode: "augment" } },
    },
  ],
};

/**
 * A grammar repository as `tree-sitter init` and `tree-sitter generate`
 * leave it: generated bindings in six languages, one hand-written C scanner,
 * two hand-written shell scripts, and a KB that uses only the Go binding.
 */
const GRAMMAR_REPO: Record<string, string> = {
  ".gitattributes": [
    "src/parser.c linguist-generated",
    "bindings/rust/* linguist-generated",
    "bindings/go/* linguist-generated",
    "bindings/node/* linguist-generated",
    "bindings/python/** linguist-generated",
    "setup.py linguist-generated",
    "",
  ].join("\n"),
  "grammar.js": "module.exports = grammar({});\n",
  "src/parser.c": "/* Automatically @generated by tree-sitter */\nint x;\n",
  "src/scanner.c": "#include <stdbool.h>\nbool scan(void) { return 0; }\n",
  "bindings/go/binding.go": "package tree_sitter_x\n",
  "bindings/rust/lib.rs": "pub fn language() {}\n",
  "bindings/rust/build.rs": "fn main() {}\n",
  "bindings/node/binding.cc": "#include <napi.h>\n",
  "bindings/python/x/__init__.py": "def language(): pass\n",
  "setup.py": "from setuptools import setup\n",
  "scripts/release-check.sh": "#!/usr/bin/env bash\necho ok\n",
  "scripts/release-notes.sh": "#!/usr/bin/env bash\necho notes\n",
  ".kb/symbols.yaml": [
    "symbols:",
    "  - id: SYM-go-binding",
    "    title: Language",
    "    sourceFile: bindings/go/binding.go",
    "",
  ].join("\n"),
};

describe("generated sources", () => {
  it("recognizes the generator markers at the top of a file only", () => {
    for (const header of [
      "/* Automatically @generated by tree-sitter */",
      "// Code generated by protoc-gen-go. DO NOT EDIT.",
      "/* automatically generated by rust-bindgen 0.69 */",
      "# This file is auto-generated from schema.json",
      "// <auto-generated />",
    ])
      expect(hasGeneratedHeader(`${header}\nint x;\n`)).toBe(true);
    expect(hasGeneratedHeader("int main(void) { return 0; }\n")).toBe(false);
    // A marker deep in the body is prose, not a header.
    expect(
      hasGeneratedHeader(`${"int x;\n".repeat(10)}// DO NOT EDIT below\n`),
    ).toBe(false);
  });

  it("reads linguist-generated attributes and generator headers", () => {
    const root = workspace(GRAMMAR_REPO);
    gitTrack(root);
    const generated = generatedSourceFiles(root, [
      "src/parser.c",
      "src/scanner.c",
      "bindings/go/binding.go",
      "bindings/rust/lib.rs",
      "scripts/release-check.sh",
    ]);
    expect([...generated].sort()).toEqual([
      "bindings/go/binding.go",
      "bindings/rust/lib.rs",
      "src/parser.c",
    ]);
  });

  it("finds the generated files the KB names as whole paths", () => {
    const root = workspace({
      ".kb/symbols.yaml":
        "sourceFile: bindings/go/binding.go\nother: src/parser.cc\n",
    });
    expect([
      ...kbReferencedFiles(
        root,
        [".kb/symbols.yaml"],
        ["bindings/go/binding.go", "src/parser.c", "bindings/rust/lib.rs"],
      ),
    ]).toEqual(["bindings/go/binding.go"]);
  });
});

describe("which packs doctor asks for", () => {
  it("counts a generated file only when the KB references it", () => {
    const files = [
      "bindings/go/binding.go",
      "bindings/rust/lib.rs",
      "src/scanner.c",
    ];
    const suggestion = referenceLanguageSuggestion(
      files,
      symbolsOnly as never,
      () => null,
      new Map(),
      new Set(),
      true,
      {
        generated: new Set(["bindings/go/binding.go", "bindings/rust/lib.rs"]),
        referenced: new Set(["bindings/go/binding.go"]),
      },
    );
    expect(suggestion?.packs).toEqual(["kibi-lang-go", "kibi-lang-c"]);
    expect(
      describeReferenceLanguageSuggestion(
        suggestion as NonNullable<typeof suggestion>,
      ),
    ).toStartWith(
      "1 Go (generated, used by the KB) source file(s) for source proofs and symbols, and 1 C for symbols only; kibi-plugin-treesitter is active for symbols but not for source proofs",
    );
  });

  it("never asks for a pack the project declined", () => {
    const suggestion = referenceLanguageSuggestion(
      ["src/scanner.c", "scripts/release.sh", "cmd/main.go"],
      {
        ...symbolsOnly,
        declinedLanguagePacks: ["kibi-lang-bash", "kibi-lang-go"],
      } as never,
      () => null,
    );
    expect(suggestion?.packs).toEqual(["kibi-lang-c"]);
    expect(
      referenceLanguageSuggestion(
        ["scripts/release.sh"],
        { declinedLanguagePacks: ["kibi-lang-bash"] },
        () => null,
      ),
    ).toBeNull();
  });

  it("asks a grammar repository only for the packs its own code and KB need", () => {
    const root = workspace({
      ...GRAMMAR_REPO,
      "package.json": JSON.stringify({ name: "g", version: "1.0.0" }),
    });
    gitTrack(root);
    const note = workspaceReferenceLanguageNote(root) as string;
    expect(note).toStartWith(
      "1 Go (generated, used by the KB) source file(s) for source proofs and symbols, and 1 C, 2 Bash for symbols only; they need kibi-plugin-treesitter and the grammar pack(s) kibi-lang-go, kibi-lang-c, kibi-lang-bash:",
    );
    expect(note).toContain(
      "6 generated file(s) are not counted (linguist-generated or a generator header) unless the KB references them.",
    );
    expect(note).toEndWith(
      'list it in package.json kibi.declinedLanguagePacks (for example "declinedLanguagePacks": ["kibi-lang-go"]); staged changes to files in that language then get a whole-file review instead of blocking.',
    );
    expect(workspacePackRelevance(root, ["src/scanner.c"]).generated.size).toBe(
      0,
    );

    fs.writeFileSync(
      path.join(root, "package.json"),
      JSON.stringify({
        name: "g",
        version: "1.0.0",
        kibi: { declinedLanguagePacks: ["kibi-lang-c", "kibi-lang-bash"] },
      }),
    );
    expect(workspaceReferenceLanguageNote(root)).toStartWith(
      "1 Go (generated, used by the KB) source file(s);",
    );
  });
});

/** A service whose only analyzer refuses every file for a missing pack. */
function packlessService(
  waiver?: (file: string, content: string, pack: string) => string | null,
): SourceAnalysisService {
  return new SourceAnalysisService({
    registry: new CapabilityRegistry({ workspaceRoot: tmpdir() }),
    ...(waiver ? { languagePackWaiver: waiver } : {}),
    resolveExtractorsV2: async () => ({
      builtin: {
        pluginId: "kibi-plugin-treesitter",
        pluginVersion: "3.0.0",
        packageName: null,
        mode: "builtin",
        external: false,
        permissions: { network: false, metered: false, secrets: [] },
        capability: {
          id: "kibi-plugin-treesitter.tree-sitter.v2",
          supports: () => true,
          analyze: async (input: { path: string }) => ({
            contractVersion: "kibi.symbol-extractor.v2" as const,
            status: "unsupported" as const,
            sourceFile: input.path,
            language: "rust",
            module: {
              title: "m",
              language: "rust",
              analysisMode: "parser" as const,
            },
            symbols: [],
            diagnostics: [
              {
                code: "TREESITTER_LANGUAGE_PACK_MISSING",
                message:
                  "Rust files need kibi-lang-rust 1.0.0, which is not installed. Run: npm install --save-dev kibi-lang-rust@1.0.0",
              },
            ],
            uncoveredRanges: [],
          }),
        },
        stamp: {
          pluginId: "kibi-plugin-treesitter",
          pluginVersion: "3.0.0",
          capability: "kibi.symbol-extractor.v2",
          mode: "augment",
          external: false,
          network: false,
          metered: false,
        },
      },
      replace: null,
      augment: [],
      shadow: [],
    }),
  } as ConstructorParameters<typeof SourceAnalysisService>[0]);
}

const obligation = (
  result: Awaited<ReturnType<SourceAnalysisService["analyzeTextV2"]>>,
) =>
  analysisObligation(
    "after",
    {
      status: result.status,
      diagnosticCodes: result.diagnostics.map((item) => item.code),
      uncoveredRanges: result.uncoveredRanges,
    },
    [{ start: 1, end: 1 }],
  ).kind;

describe("staged changes to files whose pack is not needed", () => {
  it("blocks a hand-written file until its pack is installed", async () => {
    const root = workspace(GRAMMAR_REPO);
    gitTrack(root);
    const service = packlessService(languagePackWaiver(root, {}));
    const result = await service.analyzeTextV2("src/main.rs", "fn main() {}\n");
    expect(result.diagnostics[0]?.code).toBe(
      "TREESITTER_LANGUAGE_PACK_MISSING",
    );
    expect(obligation(result)).toBe("blocked");
  });

  it("asks for a whole-file review of a declined or generated file instead", async () => {
    const root = workspace(GRAMMAR_REPO);
    gitTrack(root);
    const declined = packlessService(
      languagePackWaiver(root, { declinedLanguagePacks: ["kibi-lang-rust"] }),
    );
    const own = await declined.analyzeTextV2("src/main.rs", "fn main() {}\n");
    expect(own.diagnostics.map((item) => item.code)).toEqual([
      "language_pack_not_required",
    ]);
    expect(own.diagnostics[0]?.message).toContain(
      "kibi-lang-rust is listed in package.json kibi.declinedLanguagePacks",
    );
    expect(obligation(own)).toBe("unsupported_review");

    const generated = packlessService(languagePackWaiver(root, {}));
    const byAttribute = await generated.analyzeTextV2(
      "bindings/rust/lib.rs",
      "pub fn language() {}\n",
    );
    expect(byAttribute.diagnostics[0]?.message).toContain(
      "bindings/rust/lib.rs is generated",
    );
    expect(obligation(byAttribute)).toBe("unsupported_review");
    const byHeader = await generated.analyzeTextV2(
      "src/gen.rs",
      "// Code generated by build.rs. DO NOT EDIT.\npub fn x() {}\n",
    );
    expect(obligation(byHeader)).toBe("unsupported_review");
  });

  it("does not let a change decline the pack of the source it changes", () => {
    const root = workspace({
      "package.json": JSON.stringify({
        name: "g",
        version: "1.0.0",
        kibi: { declinedLanguagePacks: ["kibi-lang-c"] },
      }),
      "src/scanner.c": "int a;\n",
    });
    gitTrack(root);
    git(root, "commit", "-qm", "base");
    fs.writeFileSync(
      path.join(root, "package.json"),
      JSON.stringify({
        name: "g",
        version: "1.0.0",
        kibi: { declinedLanguagePacks: ["kibi-lang-c", "kibi-lang-rust"] },
      }),
    );
    fs.writeFileSync(path.join(root, "src/lib.rs"), "fn a() {}\n");
    git(root, "add", "-A");
    expect(
      readSnapshotSourceConfig(captureStagedSnapshot(root))
        .declinedLanguagePacks,
    ).toEqual(["kibi-lang-c"]);
  });
});
