// executable_for TEST-kibi-tree-sitter-language-packs
import { afterEach, describe, expect, it } from "bun:test";
import fs from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import {
  describeReferenceLanguageSuggestion,
  referenceLanguageSuggestion,
  workspacePackRelevance,
} from "../../src/plugins/reference-language-suggestion.js";

const TREESITTER = "kibi-plugin-treesitter";
const REFS = "kibi.reference-extractor.v1";
const SYMBOLS = "kibi.symbol-extractor.v2";

const roots: string[] = [];
afterEach(() => {
  for (const root of roots.splice(0))
    fs.rmSync(root, { recursive: true, force: true });
});

function workspace(files: Record<string, string>): string {
  const root = fs.mkdtempSync(path.join(tmpdir(), "kibi-suggestion-"));
  roots.push(root);
  for (const [relative, content] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(root, relative)), { recursive: true });
    fs.writeFileSync(path.join(root, relative), content);
  }
  return root;
}

describe("reference language suggestion", () => {
  it("leaves out the files of a declined pack and keeps the others", () => {
    const suggestion = referenceLanguageSuggestion(
      ["cmd/a.go", "lib/b.rb", "README.md"],
      { declinedLanguagePacks: ["kibi-lang-ruby"] },
    );
    expect(suggestion?.languages).toEqual([
      { name: "Go", files: 1, proofs: true },
    ]);
    expect(suggestion?.packs).toEqual(["kibi-lang-go"]);
    expect(
      referenceLanguageSuggestion(["lib/b.rb"], {
        declinedLanguagePacks: ["kibi-lang-ruby"],
      }),
    ).toBeNull();
    expect(referenceLanguageSuggestion(["lib/b.rb"], {})?.languages).toEqual([
      { name: "Ruby", files: 1 },
    ]);
  });

  it("marks a language generated and used by the KB only when every counted file is", () => {
    const relevance = {
      generated: new Set(["gen/a.go", "gen/b.rb"]),
      referenced: new Set(["gen/a.go", "gen/b.rb"]),
    };
    const suggestion = referenceLanguageSuggestion(
      ["gen/a.go", "cmd/c.go", "gen/b.rb"],
      {},
      () => null,
      new Map(),
      new Set(),
      true,
      relevance,
    );
    expect(suggestion?.languages).toEqual([
      { name: "Go", files: 2, proofs: true },
      { name: "Ruby", files: 1, generatedUsedByKb: true },
    ]);
  });

  it("names proof and symbol-only languages apart when both are suggested", () => {
    const suggestion = referenceLanguageSuggestion(
      ["cmd/a.go", "svc/A.java", "lib/b.rb", "tool/c.py"],
      {},
    );
    if (suggestion === null) throw new Error("expected a suggestion");
    expect(suggestion.capabilities).toEqual([REFS, SYMBOLS]);
    const entry = JSON.stringify({
      package: TREESITTER,
      capabilities: {
        [REFS]: { mode: "augment" },
        [SYMBOLS]: { mode: "augment" },
      },
    });
    expect(describeReferenceLanguageSuggestion(suggestion)).toBe(
      `1 Go, 1 Java source file(s) for source proofs and symbols, and 1 Ruby, 1 Python for symbols only; they need ${TREESITTER} and the grammar pack(s) kibi-lang-go, kibi-lang-java, kibi-lang-ruby, kibi-lang-python: npm install --save-dev ${TREESITTER} kibi-lang-go kibi-lang-java kibi-lang-ruby kibi-lang-python, then add this entry to package.json "kibi": { "plugins": [ ${entry} ] }`,
    );
  });
});

describe("workspace pack relevance", () => {
  it("judges only production files a pack reads, with the project's generatedPaths", () => {
    const header = "// Code generated by tool. DO NOT EDIT.\n";
    const root = workspace({
      "tests/gen.go": header,
      "README.md": "<!-- @generated -->\n",
      "gen/a.go": "package gen\n",
      "src/b.go": header,
      "src/c.go": "package src\n",
      ".kb/symbols.yaml": "sourceFile: src/b.go\n",
    });
    const files = [
      "tests/gen.go",
      "README.md",
      "gen/a.go",
      "src/b.go",
      "src/c.go",
      ".kb/symbols.yaml",
    ];
    const relevance = workspacePackRelevance(root, files, {
      generatedPaths: ["gen/**"],
    });
    expect([...relevance.generated].sort()).toEqual(["gen/a.go", "src/b.go"]);
    expect([...relevance.referenced]).toEqual(["src/b.go"]);
    expect([...workspacePackRelevance(root, files).generated]).toEqual([
      "src/b.go",
    ]);
  });
});
