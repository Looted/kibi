import { afterEach, describe, expect, mock, spyOn, test } from "bun:test";
import { mkdirSync, symlinkSync, writeFileSync } from "node:fs";
import path from "node:path";
import { checkCommand } from "../../src/commands/check.js";
import * as detachedSnapshot from "../../src/runtime/detached-snapshot.js";
import * as stagedConsistency from "../../src/traceability/staged-consistency.js";
import * as inventoryDrift from "../../src/traceability/staged-inventory-drift.js";
import * as stagedSymbols from "../../src/traceability/staged-symbols-manifest.js";
import * as branchResolver from "../../src/utils/branch-resolver.js";
import {
  captureIo,
  createGitWorkspace,
  git,
  isolateKibiEnv,
  removeTempDir,
  restoreWorkspaceCwd,
  withCwd,
} from "../helpers/in-process-workspace.js";

const roots: string[] = [];
const restores: Array<() => void> = [];

afterEach(() => {
  mock.restore();
  for (const restore of restores.splice(0)) restore();
  restoreWorkspaceCwd();
  for (const root of roots.splice(0)) removeTempDir(root);
});

function repo(
  files: Record<string, string>,
  commit: Record<string, string> = {},
): string {
  restores.push(isolateKibiEnv());
  const root = createGitWorkspace("main");
  roots.push(root);
  const put = (entries: Record<string, string>) => {
    for (const [relative, content] of Object.entries(entries)) {
      const absolute = path.join(root, relative);
      mkdirSync(path.dirname(absolute), { recursive: true });
      writeFileSync(absolute, content);
    }
  };
  if (Object.keys(commit).length > 0) {
    put(commit);
    git(root, "add -A");
    git(root, "commit --no-verify -qm base");
  }
  put(files);
  git(root, "add -A");
  return root;
}

async function staged(root: string, options: Record<string, unknown> = {}) {
  const io = captureIo();
  try {
    const result = await withCwd(root, () =>
      checkCommand({
        staged: true,
        kbPath: path.join(root, "kb-store"),
        ...options,
      }),
    );
    return { result, io };
  } finally {
    io.restore();
  }
}

const REQ =
  "---\nid: REQ-1\ntitle: Req one\nstatus: open\ntype: req\n---\n\nThe system does one thing.\n\n## Context\n\nWhy it matters.\n";
const SOURCE = "export function a() {\n  return 1;\n}\n";

describe("checkCommand --staged symbol extraction", () => {
  test("rejects a symbol linked to a requirement missing from the snapshot", async () => {
    const root = repo({
      "src/a.ts": `// implements REQ-MISSING\n${SOURCE}`,
    });
    const { result, io } = await staged(root);
    expect(result).toStrictEqual({ exitCode: 1 });
    expect(io.errorText()).toContain(
      "Error running staged validation: Error extracting symbols from staged file src/a.ts: Symbol a references a requirement absent from the captured knowledge snapshot: REQ-MISSING",
    );
  });

  test("notes symbols of a generated file that need no requirement link", async () => {
    const header = "// Code generated by tool. DO NOT EDIT.\n";
    const root = repo(
      { "src/gen.ts": `${header}export function g() {\n  return 2;\n}\n` },
      { "src/gen.ts": `${header}export function g() {\n  return 1;\n}\n` },
    );
    const { io } = await staged(root);
    expect(io.logText()).toContain(
      "Generated files: symbols without a requirement link in src/gen.ts are not checked for one",
    );
  });

  test("reads manifest symbol sources from the snapshot tree", async () => {
    const root = repo(
      {
        ".kb/symbols.yaml":
          "symbols:\n  - id: SYM-1\n    title: a\n    sourceFile: src/a.ts\n    links: [REQ-1]\n  - id: SYM-2\n    title: a\n    sourceFile: src/a.ts\n  - id: SYM-3\n    title: b\n    sourceFile: src/missing.ts\n",
      },
      { ".kb/requirements/REQ-1.md": REQ, "src/a.ts": SOURCE },
    );
    const { result, io } = await staged(root);
    expect(result).toStrictEqual({ exitCode: 1 });
    expect(io.logText()).toContain(
      "Symbols SYM-1, SYM-2 share title a and source src/a.ts without distinct coordinate evidence.",
    );
  });

  test("refuses a manifest symbol whose snapshot source is not a regular file", async () => {
    const root = repo(
      {
        ".kb/symbols.yaml":
          "symbols:\n  - id: SYM-L\n    title: a\n    sourceFile: src/link.ts\n",
      },
      { "src/a.ts": SOURCE },
    );
    symlinkSync("a.ts", path.join(root, "src", "link.ts"));
    git(root, "add -A");
    const { result, io } = await staged(root);
    expect(result).toStrictEqual({ exitCode: 1 });
    expect(io.errorText()).toContain(
      "Snapshot symbol source is not a regular file: src/link.ts",
    );
  });

  test("notes symbols the staged migration changed only mechanically", async () => {
    const root = repo({ "src/a.ts": SOURCE });
    const real = stagedSymbols.collectStagedAuthoredSymbolsManifestEvidence;
    spyOn(
      stagedSymbols,
      "collectStagedAuthoredSymbolsManifestEvidence",
    ).mockImplementation((options) => ({
      ...real(options),
      migrationOnlyEntityIds: ["S1", "S2", "S3", "S4", "S5", "S6", "S7"],
    }));
    const { io } = await staged(root);
    expect(io.logText()).toContain("S1, S2, S3, S4, S5 and 2 more");
  });
});

describe("checkCommand --staged knowledge gates", () => {
  test("blocks consistency violations the staged knowledge introduces", async () => {
    const root = repo({ ".kb/requirements/REQ-1.md": REQ });
    spyOn(
      stagedConsistency,
      "collectIntroducedConsistencyViolations",
    ).mockResolvedValue([
      {
        rule: "domain-contradictions",
        entityId: "REQ-1",
        description: "REQ-1 contradicts REQ-2",
      },
    ] as never);
    const { result, io } = await staged(root);
    expect(result).toStrictEqual({ exitCode: 1 });
    expect(io.logText()).toContain("[domain-contradictions] REQ-1");
    const dry = await staged(root, { dryRun: true });
    expect(dry.result).toStrictEqual({ exitCode: 0 });
  });

  test("blocks staged requirements whose inventory drifted", async () => {
    const root = repo(
      { ".kb/requirements/REQ-1.md": REQ.replace("one thing", "two things") },
      { ".kb/requirements/REQ-1.md": REQ },
    );
    const bases: Array<string | null> = [];
    spyOn(inventoryDrift, "stagedInventoryDriftViolations").mockImplementation(
      (input) => {
        bases.push(input.readBase(".kb/requirements/REQ-1.md"));
        bases.push(input.readBase(".kb/requirements/REQ-NONE.md"));
        return [
          { rule: "semantic-inventory", message: "REQ-1 prose changed" },
        ] as never;
      },
    );
    const { result, io } = await staged(root);
    expect(result).toStrictEqual({ exitCode: 1 });
    expect(bases).toStrictEqual([REQ, null]);
    expect(io.logText()).toContain(
      "1 staged requirement(s) have a semantic inventory that is missing or no longer matches their prose:\n  REQ-1 prose changed",
    );
    const dry = await staged(root, { dryRun: true });
    expect(dry.result).toStrictEqual({ exitCode: 0 });
  });
});

describe("checkCommand on a detached checkout", () => {
  test("warns and refreshes the read-only snapshot before checking", async () => {
    const root = repo({});
    spyOn(branchResolver, "resolveReadBranchAttachment").mockReturnValue({
      kbBranch: branchResolver.DETACHED_SNAPSHOT_KB_BRANCH,
      storePath: path.join(root, "snapshot-store"),
      readOnly: { notice: "detached checkout: reading a snapshot" },
    } as never);
    const refreshed = spyOn(
      detachedSnapshot,
      "refreshDetachedSnapshot",
    ).mockResolvedValue(undefined as never);
    const io = captureIo();
    restores.push(io.restore);
    const result = await withCwd(root, () => checkCommand({ staged: true }));
    expect(result).toStrictEqual({ exitCode: 0 });
    expect(io.warns).toContain("[KIBI] detached checkout: reading a snapshot");
    expect(refreshed).toHaveBeenCalledTimes(1);
  });
});
